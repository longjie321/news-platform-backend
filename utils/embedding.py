# ============================================================
# 区域：向量化（embedding）
# 作用：把文字翻译成向量（一串数字），意思相近的文字向量也相近
#   为什么需要它：计算机不懂"意思"，只懂数字
#   把问题和新闻都变成向量后，"谁和谁意思相近"就变成了"哪两个向量距离近"
#   实现方式：调用硅基流动的 bge 向量化接口（OpenAI 兼容格式）
#     bge = BAAI General Embedding，智源出的中文向量模型，免费、中文效果好
#     本来计划在本地跑模型，但这台电脑的系统策略拦截了 torch 的 DLL 加载
#     所以改用 API：效果一样、代码更短，还不用装 torch
#
# ============================================================
# 【学习版说明书】
# ============================================================
# 本文件是"逐词精讲版"。每行代码下面固定两段：
#   # 做什么：  一句话说清这行在干什么
#   # 逐词：    把这行里每个"词"拆开 —— 它是什么、从哪来、原意是什么
#
# 标签：【内置】不用 import ｜【标准库】自带模块要 import ｜【三方库】pip 装的
#       【本地】项目自己写的 ｜【自起名】只是自己起的名字，不是任何 API
#
# 这个文件是一个完整的"调外部 HTTP 接口"的范例，值得记住的套路：
#   ① 拼 URL（f-string）→ ② 带请求头（鉴权 + 内容类型）→ ③ 发 JSON 正文
#   → ④ 检查状态码 → ⑤ 解析返回的 JSON → ⑥ 取自己要的字段
# 以后你调任何第三方接口，基本都是这六步。
# ============================================================

