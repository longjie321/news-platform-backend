import httpx
# 做什么：把三个字母的 httpx 库整个拿进来
# 逐词：
#   import  【内置】"导入"关键字
#   httpx   【三方库】拆开：http（超文本传输协议）+ x（表示"扩展版/加强版"）
#           → 一个比 requests 更好用的 HTTP 客户端库，还能做异步。
#           它是 pip 装的（在 requirements.txt 里）
# ⚠️ 这个库有两种用法，本文件和 routers/ragchat.py 各用一种，别搞混：
#     本文件：httpx.post(...)          → **同步**版，直接调用、不用 await
#     ragchat：httpx.AsyncClient(...)  → **异步**版，所有调用都要 await
#   还有一个后缀区别：.post() 是"一次性发完等响应"；
#     client.stream() 是"流式读"（一段一段收，打字机效果就靠它）

from config.rag_conf import EMBEDDING_API_KEY, EMBEDDING_BASE_URL, EMBEDDING_MODEL
# 做什么：从配置中心取出三个常量
# 逐词：
#   from / config / .rag_conf / import  【内置 + 本地】"从 config/rag_conf.py 里取出"
#   EMBEDDING_API_KEY   【本地】硅基流动的密钥（从 .env 读进环境变量再取出来）
#   EMBEDDING_BASE_URL  【本地】接口根地址，默认 "https://api.siliconflow.cn/v1"
#   EMBEDDING_MODEL     【本地】用哪个模型，默认 "BAAI/bge-m3"
# 来源说明：这三个的名字都是**项目自己起的**（在 rag_conf.py 里定义），不是库提供的
# 想改它们，去 config/rag_conf.py 改，改这一个文件就够

# ------------------------------------------------------------
# 常量
# ------------------------------------------------------------

BATCH_SIZE = 32
# 做什么：定义"每批送多少段文本"这个常量
# 逐词：
#   BATCH         【自起名】"一批" —— 把大任务拆成一小批一小批处理，这个做法叫"批处理"
#   SIZE          【通用词】"大小、数量"
#   = 32          【内置】赋值 + 数字
# 为什么不一次全送：几百段文本一次送过去，容易被对方限流（rate limit）或者超时；
#   分批就稳得多。32 是经验折中值（太小则请求次数多、太慢；太大则容易超时）
# 常量命名用全大写是惯例（意思是"定好就不改"）

# ------------------------------------------------------------
# 内部函数：调一次接口，转一批
# ------------------------------------------------------------


def _embed_batch(texts: list) -> list:
    # 做什么：定义函数，把一批文本转成向量（这个函数不对外，只在本文件内部用）
    # 逐词：
    #   def          【内置】define，"定义函数"
    #   _embed_batch 【自起名】拆开：
    #                _（开头下划线 = "内部专用"，提醒外面别直接调它）
    #                embed（嵌入）+ batch（一批）
    #                → "转一批嵌入向量"。这不是任何库的 API，是项目自己起的名字
    #   texts: list  【自起名 + 内置】texts 是参数名（"多段文本"）；: list 是类型标注（该传列表）
    #   -> list      【内置】返回类型标注：返回一个列表（一堆向量）
    """调一次接口，把一批文本转成向量，返回向量列表（内部函数，外面不直接用）"""
    # 做什么：docstring（文档字符串），IDE 悬停时显示
    # 逐词："""...""" 【内置】三引号字符串；写在函数第一句就自动变成说明文档
    resp = httpx.post(
        # 做什么：发一个 HTTP POST 请求，把响应对象存进 resp
        # 逐词：
        #   resp        【自起名】response（响应）的缩写 → 代表"对方返回给我的东西"
        #   =           【内置】赋值
        #   httpx       【三方库】上面 import 进来的库
        #   .post(...)  【三方库】发 POST 请求的方法。
        #               ⚠️ GET / POST 的区别（面试会问）：
        #                  GET  = "我要拿数据"，参数放在 URL 里，可被缓存、可重复
        #                  POST = "我要提交数据"，正文放在 body 里，不缓存
        #                  这里是 POST，因为我们要把"待转换的文本"提交给对方
        #   ⚠️ 括号一直到第 59 行才闭合 —— 这就是"括号没闭合时 Python 允许换行"的写法，
        #      参数才好在每个参数一行地写清楚
        f"{EMBEDDING_BASE_URL}/embeddings",
        # 做什么：拼出完整的接口地址，作为第一个位置参数（URL）
        # 逐词：
        #   f"..."              【内置】f-string：字符串前面加 f，里面 {变量} 会替换成变量的值
        #   {EMBEDDING_BASE_URL}【本地】比如 https://api.siliconflow.cn/v1
        #   /embeddings         【服务商规定】接口路径。
        #                       embed（嵌入）+ ings → "嵌入接口"
        #                       ⚠️ 这个路径名是硅基流动定的，不能自己改
        #   拼完长这样：https://api.siliconflow.cn/v1/embeddings
        headers={
            # 做什么：设置"请求头" —— 告诉对方"我是谁、我发的是什么格式"
            # 逐词：
            #   headers=  【三方库】参数名。header（头部、头部信息）→ HTTP 请求的"抬头信息"
            #   { ... }   【内置】花括号 = 字典（键值对），HTTP 头本身就是一堆"键: 值"
            "Authorization": f"Bearer {EMBEDDING_API_KEY}",
            # 做什么：带鉴权信息，证明"是我，我有权限调用"
            # 逐词：
            #   "Authorization"  【HTTP 标准字段名】authorization（授权）。必须拼写正确
            #   f"Bearer ..."    【HTTP 标准格式】拆开：
            #       Bearer = "持有者"（英语里"拿票的人"叫 bearer）。
            #       这是 HTTP 鉴权的固定约定词，后面必须跟一个空格，然后是密钥
            #       ⚠️ "Bearer " 后面那个空格不能漏，漏了对方会返回 401
            #   {EMBEDDING_API_KEY}  【本地】从配置读出来的密钥
            # 整行效果：Authorization: Bearer sk-xxxxxxxx
            "Content-Type": "application/json",
            # 做什么：告诉对方"我发过去的正文是 JSON 格式"
            # 逐词：
            #   "Content-Type"  【HTTP 标准字段名】内容类型
            #   "application/json"  【HTTP 标准取值】拆开：
            #       application = 应用类数据（不是 text、image 那种）
            #       json        = JavaScript Object Notation
            #       ⚠️ 不写这个头，有些服务端会拒绝或者解析失败
        },
        # 这里逗号结束 headers 这个参数
        json={
            # 做什么：设置"请求正文"，也就是要发给对方的数据
            # 逐词：
            #   json=  【三方库】httpx 提供的**便利参数**：你给它一个 Python 字典，
            #          它自动帮你转成 JSON 字符串，并顺便设好 Content-Type
            #          ⚠️ 对比另一种写法 data=：data 是发"表单格式"（key=value&key=value）。
            #             这个接口要 JSON，所以必须用 json=
            #   { ... }  【内置】花括号 = 字典
            "model": EMBEDDING_MODEL,
            # 逐词：
            #   "model"          【服务商规定的字段名】"用哪个模型"
            #   : EMBEDDING_MODEL 【本地】比如 "BAAI/bge-m3"
            # 用哪个模型（BAAI/bge-m3）—— 名字来自 config/rag_conf.py
            "input": texts,
            # 逐词：
            #   "input"  【服务商规定的字段名】输入。
            #            ⚠️ 键名就叫 input，是接口规定的，不能改成 texts
            #   texts    【自起名】函数参数，也就是"这一批要转的文本"，是个列表
            # 要转成向量的文本列表。注意键名就叫 input（这是接口规定的，不能自己改名）
            "encoding_format": "float",
            # 逐词：
            #   "encoding_format"  【服务商规定的字段名】编码格式。
            #        encoding（编码）+ format（格式）→ "用什么格式给我返回向量"
            #   "float"            【服务商规定的取值】浮点数（小数）。
            #        另一种取值是 "base64"（用 base64 编码压成字符串，省流量但要解码）。
            #        我们要直接拿数字算距离，所以用 float
            # 向量按普通浮点数返回（float = 小数）
        },
        timeout=60,
        # 做什么：规定"最多等多少秒"，超时就报错
        # 逐词：
        #   timeout=  【三方库】参数名，单位是**秒**（60 = 60 秒）
        #   ⚠️ 为什么必须设：不设的话（或用默认值），万一对方网络卡住，
        #      这个请求会一直挂着等下去 —— 对服务来说就是"一个请求把资源占死"
        #       60 秒是权衡：正常一批 32 条几秒就回来了，60 秒已经很宽容
    )
    # 这里才是 httpx.post(...) 的收尾括号。
    # 一句话总结这次调用：POST 到 .../embeddings，带上密钥和 JSON 正文（模型名 + 文本列表）。

    if resp.status_code != 200:
        # 做什么：检查对方返回的"状态码"，不是 200 就当成失败处理
        # 逐词：
        #   if              【内置】"如果"
        #   resp            【自起名】上面那次请求的响应对象
        #   .status_code    【三方库】状态码属性。拆开：status（状态）+ code（代码）
        #                   → HTTP 状态码，200 = 成功。
        #                   常见其他的：401 密钥错、429 被限流、400 参数不对、500 对方服务器出错
        #   !=              【内置】"不等于"（! 是 not、= 是 equal）。
        #                   ⚠️ 别写成 =（赋值）或 <>（老写法）
        raise RuntimeError(f"向量化接口错误({resp.status_code}): {resp.text}")
        # 做什么：主动抛出一个错误，程序在这里中断
        # 逐词：
        #   raise        【内置】"抛出"—— 主动制造一个异常，让程序停下来
        #   RuntimeError 【内置】一种内置的异常类型。
        #                runtime（运行时）+ error → "运行期间出了不该出的问题"。
        #                为什么不用普通的 Exception：RuntimeError 语义更明确，
        #                而且调用方想"只捕获这一类错"时可以精准捕获
        #   f"..."       【内置】f-string 拼错误信息。
        #                {resp.status_code} 填状态码、{resp.text} 填对方的原始返回内容
        #   resp.text    【三方库】对方返回的**原始文本**（不是解析后的）。
        #                放进错误信息里，排查时一眼能看到对方到底说了什么
        #   ⚠️ 为什么这里选择"抛异常"而不是"返回 None"：
        #      向量化失败后面根本没法继续（没有向量就没法入库/检索），
        #      早报错比让错误藏到后面更难查的地方强得多
    # 非 200：把状态码和错误内容原样抛出
    #   常见原因：key 错了（401）、没余额了、请求格式不对（400）

    data = resp.json()["data"]
    # 做什么：把对方的返回解析成字典，并取出里面的 data 这一项
    # 逐词：
    #   data         【自起名】随便起的名字，装"那一批向量结果"
    #   resp.json()  【三方库】把响应正文（JSON 字符串）解析成 Python 的字典/列表。
    #                ⚠️ 如果对方返回的不是合法 JSON，这一步会抛异常（这也是正常的报错方式）
    #   ["data"]     【内置】字典取值：取出键为 data 的那一项
    #   接口返回的结构长这样：
    #     {"data": [{"index": 0, "embedding": [...]}, {"index": 1, "embedding": [...]}]}
    #     也就是 data 是一个列表，每个元素是"第几个 + 它的向量"
    # 返回结构：{"data": [{"index": 0, "embedding": [...]}, ...]}

    data.sort(key=lambda item: item["index"])
    # 做什么：把这个列表按 index 从小到大重新排好
    # 逐词：
    #   data        【自起名】上面取出来的列表
    #   .sort()     【内置】列表方法：**原地排序**（直接改这个列表本身，没有返回值）。
    #               ⚠️ 所以千万别写 data = data.sort() —— 那样 data 会变成 None
    #   key=        【内置】"按什么排序"。它会拿 key 算出来的值来比大小
    #   lambda item: item["index"]  【内置】lambda = "一次性小函数"，
    #               写法是 lambda 参数: 返回值。这句等价于：
    #                   def 某个名字(item):
    #                       return item["index"]
    #               意思是"给我一个结果项，我返回它的 index 字段"。
    #               ⚠️ 为什么不写 key=item["index"]：那样 item 从哪来都不知道，必须先定义参数
    # 为什么必须排：接口**不保证**返回顺序和输入顺序一致。
    #   如果不排，就可能把"第 3 段的向量"配上"第 1 段的文字"——
    #   数据和向量错位，检索结果全是错的，而且**不会报错**（典型的静默错误）

    return [item["embedding"] for item in data]
    # 做什么：把每一项的 embedding 抽出来，组成新列表返回
    # 逐词：
    #   return  【内置】返回
    #   [ ... for item in data ]  【内置】"列表推导式"：把右边列表里的每个元素加工后组成新列表。
    #                等价于：结果 = []; for item in data: 结果.append(item["embedding"])
    #   item["embedding"]  【内置】字典取值，取出这一项的向量（一串小数）
    # 只取向量本身，返回普通列表（ChromaDB 只认普通列表）

# ------------------------------------------------------------
# 对外函数：把任意条文本转成向量（内部按 32 一批循环）
# ------------------------------------------------------------


def embed_texts(texts: list) -> list:
    # 做什么：定义对外函数，接收任意长度的文本列表，返回等长的向量列表
    # 逐词：
    #   def         【内置】定义函数
    #   embed_texts 【自起名】embed（嵌入）+ texts（多段文本）。
    #               ⚠️ 注意和上面那个 _embed_batch 的区别：
    #                   _embed_batch = 内部函数（下划线开头），只管"一批"（最多 32 条）
    #                   embed_texts = 对外入口（无下划线），负责"不管多少条都能处理"（内部循环分批）
    #               这种"一个管一批、一个管全部"的分工是很常见的写法
    #   texts: list 【自起名 + 内置】参数名 + 类型标注
    #   -> list     【内置】返回类型标注
    """
    把多段文本转成向量（对外统一入口）
    texts：文本列表，比如 ["今天天气不错", "明天会下雨吗"]
    返回：向量列表，与输入一一对应
    """
    if not EMBEDDING_API_KEY:
        # 做什么：先检查"密钥配了没有"，没配就直接报错
        # 逐词：
        #   if                【内置】"如果"
        #   not               【内置】"取反"。
        #                     EMBEDDING_API_KEY 默认值是空字符串 ""，空字符串是"假值"，
        #                     所以 not 之后就是 True → 进这个分支
        #   EMBEDDING_API_KEY 【本地】从配置读来的密钥
        #   ⚠️ 为什么要在最前面就检查：这样报错信息能明确指出"是密钥没配"。
        #      不检查的话，程序会继续往下跑，最后拿到对方返回的 401，
        #      报错变成"接口错误(401)"，你还要猜半天是密钥问题还是网络问题
        raise RuntimeError("未配置 EMBEDDING_API_KEY，请在 .env 文件中设置硅基流动的密钥")
        # 逐词：
        #   raise        【内置】抛出异常
        #   RuntimeError 【内置】运行时错误类型
        #   括号里那串 【字符串】错误信息。这里故意写得很具体：
        #                说清是哪个变量没配、去哪个文件配、配的是哪家的密钥 ——
        #                好错误信息的标准就是"看的人能立刻知道怎么修"
        # 没配 key 直接给出明确提示，不让错误藏到后面才爆

    vectors = []
    # 做什么：准备一个空列表，用来攒所有向量
    # 逐词：
    #   vectors  【自起名】vector（向量）+ s → 多个向量
    #   []       【内置】空列表
    for i in range(0, len(texts), BATCH_SIZE):
        # 做什么：按 32 为步长，生成一批批的起止位置
        # 逐词：
        #   for ... in ...  【内置】遍历
        #   i               【自起名】这一批的**起始下标**（0, 32, 64, 96 …）
        #   range(起点, 终点, 步长)  【内置】生成一串整数。
        #       这里 = range(0, 总条数, 32) → 0, 32, 64, …
        #       ⚠️ 两个要点：
        #          ① 终点本身取不到（开区间），所以最后一批不会越界
        #          ② 只给 range(n) 时是 0 到 n-1；给三个参数才是"起点/终点/步长"
        # 这个循环的次数 = 总条数 ÷ 32 向上取整（例如 403 条 → 13 批）
        vectors.extend(_embed_batch(texts[i:i + BATCH_SIZE]))
        # 做什么：切出这一批，交给内部函数转换，然后把结果并进 vectors
        # 逐词：
        #   vectors            【自起名】上面那个空列表
        #   .extend(某个列表)  【内置】把参数列表里的元素**逐个**加进来。
        #        ⚠️ 和 .append 的关键区别：
        #             vectors.append([v1, v2])  → [..., [v1, v2]]（嵌套进一个列表，错了）
        #             vectors.extend([v1, v2])  → [..., v1, v2]（摊平，正确）
        #        这里要的是摊平，所以必须用 extend
        #   texts[i:i + BATCH_SIZE]  【内置】切片：从下标 i 取到 i+32（不含 i+32）。
        #         ⚠️ 如果剩下的不足 32 条，切片会**自动只给现有的**，不会报错 ——
        #            所以最后一批能正常处理，这也是这个写法比"手动算长度"更安全的地方
