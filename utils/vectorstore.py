def add(ids: list, texts: list, embeddings: list, metadatas: list):
    # 做什么：定义 add 函数，接收四个列表，把它们写进向量库
    # 逐词：
    #   def        【内置】定义函数
    #   add        【自起名】"添加" —— 这个函数名是项目自己取的
    #   ids        【自起名】id 的复数。"id" 是 identifier（标识符）的缩写 → "每块的编号"
    #   texts      【自起名】text 的复数 → "每块的正文"
    #   embeddings 【自起名】embed（嵌入）的动名词。在 AI 里它是"嵌入向量"的标准叫法，
    #              意思是"把文本映射（嵌入）到一个高维数字空间里的那串数字"
    #   metadatas  【自起名】metadata 的复数 → "每块的档案袋"
    #   : list      【内置】冒号后的 list 是**类型标注** —— 写给人/IDE 看的"这里该传列表"，
    #              Python 运行时并不会因为它而报错（真正检查的是 Pydantic 那种库）
    #   → 四个参数都是 list，是因为 Chroma 要求"一批一起写"，而不是一条条写
    """
    把切好的块写进向量库
    ids/texts/embeddings/metadatas 四个列表必须一样长，位置一一对应
    """
    _collection().upsert(
        # 做什么：拿到表对象，调用它的 upsert 方法，把这一批数据写进去
        # 逐词：
        #   _collection()  【本地】本文件上面定义的函数，括号不能少 ——
        #                  加了括号才是"调用它、拿到表对象"；不加括号只是"提到这个函数"
        #   .              【内置】点号
        #   upsert         【三方库】Chroma 集合对象的方法。这个词是造出来的缩写：
        #                  **up**date（更新）+ in**sert**（插入）→ "有就更新、没有就插入"
        #                  好处（面试会问）：同一个 id 重复写是"覆盖"而不是"多一条"，
        #                  所以建索引脚本可以反复跑，不会堆出两份数据（这叫"幂等"：
        #                  idempotent，同一个操作执行一次和执行多次的结果一样）
        ids=ids,
        # 逐词：
        #   ids=  【三方库】参数名（Chroma 规定的），值传的是上面那条参数 ids
        # 每块唯一的编号（本项目长这样：news_7_0，含义是"新闻 7 的第 0 块"）
        # 这个"可预测的 id"很关键：内容变了我们能算出旧 id 去删它
        documents=texts,
        # 逐词：
        #   documents=  【三方库】参数名。document 原意"文件、文档"，
        #               向量库把"一条文本"叫一个 document（我们叫它"块"）
        #   ⚠️ 参数名是 Chroma 定的，不能自己改成 texts —— 我们传进去的变量叫 texts 只是因为项目里这么起的名
        embeddings=embeddings,
        # 逐词：
        #   embeddings=  【三方库】参数名，要的是一串串数字（向量）
        #   值来自哪里：【本地】utils/embedding.py 的 embed_texts() 算好后由 crud/rag.py 传进来
        #   为什么不让 Chroma 自己算：因为我们的向量化走的是外部 API，得先算好再传
        metadatas=metadatas,
        # 逐词：
        #   metadatas=  【三方库】参数名（注意是复数，因为它要"一批"）
        #   档案袋里装着：news_id / title / category / content_hash
        # 为什么必须有它：检索命中时，只有靠它才能告诉用户"这个答案出自哪篇新闻"
        # ⚠️ 它的长度必须和 ids / documents 完全一样，且位置一一对应，否则会报
        #    ValueError: Unequal lengths for fields（实测过）
    )
    # upsert：同 id 重复写是覆盖，所以脚本可以反复跑，不会堆出两份数据
    # 这个函数没有 return —— 写入类操作通常不需要返回值，调用方也不接


