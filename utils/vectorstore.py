def delete_news(news_id: int):
    # 做什么：定义函数，把某篇新闻的所有块删掉
    # 逐词：
    #   delete_news  【自起名】delete（删除）+ news（新闻）
    #   news_id: int 【自起名 + 内置】参数名是自起的，: int 是类型标注（说明传整数）
    """把某篇新闻的旧块全删掉（新闻内容改了要重新切块时用）"""
    _collection().delete(where={"news_id": news_id})
    # 做什么：按条件删掉匹配的行（表本身保留）
    # 逐词：
    #   .delete()       【三方库】集合对象的方法：删数据
    #   where=          【三方库】参数名："按什么条件删"。
    #                   这里的 where 是英文"在什么条件下"的意思，不是 SQL 里那个 WHERE 的拷贝，但含义一样
    #   {"news_id": news_id}  【内置】字典表示条件：键是字段名，值是"要匹配的值"
    #                   → 把所有 news_id 等于这个值的块删掉
    #   注意右值那个 news_id 是函数参数（哪篇新闻），不是字典的键 —— 长得像但位置不同
    #   ⚠️ 和 reset() 的区别：delete 是"删几行"，reset 是"删整张表"
    # 按档案袋里的 news_id 删，比按 id 前缀删更直观
    # 调用方：【本地】crud/rag.py 的 build_index()，一处是"内容变了先删旧块"，
    #        另一处是"清 MySQL 里已删掉的孤儿数据"


