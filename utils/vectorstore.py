# 第七部分：清空整张表（reset）
# ------------------------------------------------------------


def reset():
    # 做什么：定义函数，把整个集合（表）删掉
    # 逐词：
    #   reset  【自起名】"重置/复位"。这里不传参数、不返回值
    """清空整个集合（全量重建索引前用）"""
    global _client
    # 做什么：声明要改的是模块级那个 _client
    # 逐词：同上面 _collection() 里那句，理由一样
    if _client is None:
        # 【内置】注意：这里不能调 _collection()，因为那个函数会顺手"建一张表"，
        #   而我们的目的正是"把表删掉" —— 先建再删属于白干
        _client = chromadb.PersistentClient(path=CHROMA_DIR)
        # 做什么：确保连接已经建立
        # 逐词：和 _collection() 里那句一模一样（chromadb.PersistentClient + path=CHROMA_DIR）
    # 先确保连接已建立

    try:
        # 做什么：包住"可能出错的那一行"
        # 逐词：
        #   try    【内置】"尝试" —— 把可能出错的代码放这里，一旦出错就跳到下面的 except，
        #          而不是让整个程序崩掉
        #   :      冒号是 Python 里"接下来是一个代码块"的标志（后面要缩进）
        _client.delete_collection(name=COLLECTION_NAME)
        # 做什么：删掉整张集合表（表 + 里面所有数据）—— 这就是"清空"
        # 逐词：
        #   .delete_collection()  【三方库】删表的方法。注意它是在 **_client** 上调用，
        #                          不是在 collection 上 —— 因为"删表"这件事属于"客户端"那一族
        #                          （客户端管"有哪些表"；集合对象管"表里的数据"）
        #   name=COLLECTION_NAME  【三方库参数 + 本地常量】要删哪张表
    except Exception:
        # 做什么：捕获出错的情况
        # 逐词：
        #   except     【内置】"除了…情况" —— 捕获异常的入口
        #   Exception  【内置】Python 里"几乎所有异常的父类"。写它 = "不管什么错都接住"
        #              ⚠️ 更精确的写法是只捕获 chromadb 自己的 NotFoundError，
        #                 那样别的错（比如磁盘坏了）还能正常暴露出来
        pass
        # 做什么：什么都不做
        # 逐词：
        #   pass  【内置】"占位语句"。Python 语法不允许 if/except/for 块里空着，
        #          什么都不想干时就写 pass
    # 集合本来就不存在时会报错（实测这里的 chromadb 抛 NotFoundError），忽略即可 ——
    # 因为这里的目标是"确保它是空的"：本来就不存在，等于目标已经达成
    # ⚠️ 注意：平时 except ...: pass 是"反模式"（会把错误全吞掉，出问题查不到原因），
    #   只有像这里一样"报错和成功的结果等价"时才允许这么写
    # 调用方：【本地】crud/rag.py 的 build_index()，只在 rebuild=True（全量重建）时才会调用


