# 区域：向量数据库封装（utils 层）
# 作用：把"文本 + 向量 + 来源信息"存进 ChromaDB，并按"意思相近"查找
#   对外提供 6 个函数：add / search / get_hashes / delete_news / reset / count
#
# 关键理解（面试会问）：
#   ① 为什么不用 MySQL 存向量？
#      MySQL 只会"等于"和"大于小于"，没有"找最像的"这种能力；
#      向量库专门做"最近邻搜索"，几百万条也能毫秒级返回
#   ② Chroma 返回的是 distance（距离，越小越像），不是相似度！
#      所以必须换算：相似度 = 1 - 距离。这一步最容易写反，写反了就成了"最像的排最后"
#   ③ upsert = 有就覆盖、没有就插入（幂等），所以建索引脚本可以反复跑
#
