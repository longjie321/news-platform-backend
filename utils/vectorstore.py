_client = None
# 做什么：定义一个模块级变量 _client，初始值是"空"
# 逐词：
#   _client   【自起名】拆开：_（下划线）+ client（客户端）
#             · client 原意"客户、委托人"，在编程里指"替你去跟某个服务打交道的对象"。
#               你项目里一共有好几个这样的角色：redis_client（跟 Redis 打交道）、
#               httpx.AsyncClient（跟 DeepSeek 打交道）、这里的 chromadb 客户端（跟向量库打交道）
#             · 开头的下划线是 Python 的**命名约定**：表示"内部专用，别从外面动我"。
#               它不是语法锁（外面照样能访问），只是提醒
#   =         【内置】赋值号：把右边的值装进左边的变量
#             ⚠️ 判断"相等"要用两个等号 ==，一个等号永远是赋值，这点最容易看错
#   None      【内置】Python 里表示"什么都没有"的那个值，类型是 NoneType
#             ⚠️ 它和空字符串 "" 不一样："" 是"有一个字符串，只是长度是 0"；
#                None 是"连这个东西都没有"。两者 bool() 都是 False，特别容易混
# 为什么要它：建连接是"重活"（要开文件、建目录）。放到模块级 + 下面那句判断，
#   就能做到"用到才连、而且全进程只连一次"

# 这个文件后面所有函数都会调 _collection()，它做三件事：
#   ① 第一次调用时才真的连库（懒加载）
#   ② 之后每次调用都复用同一个连接
#   ③ 确保那张"表"存在（不存在就自动建）


def _collection():
    # 做什么：定义函数 _collection（不带参数），它返回"一张表对象"
    # 逐词：
    #   def         【内置】define 的缩写，"定义函数"的关键字
    #   _collection 【自起名】下划线 = 内部专用；collection 原意"收藏、集合"，
    #               在向量库里指"一个集合"，地位相当于 MySQL 里的一张表
    #   ()          【内置】括号里放参数。这里是空的 = 不需要传任何东西
    #               调用它时必须写 _collection()，括号不能少（少了就只是"提到这个函数"，不是"执行它"）
    """拿到集合对象：第一次调用时才连接数据库，集合不存在会自动建"""
    # 做什么：这是 docstring（文档字符串），写在函数第一句
    # 逐词：
    #   """..."""   【内置】三引号包起来的字符串，出现位置有讲究：
    #               写在函数/类/文件的第一句 → 自动成为"说明文档"，
    #               IDE 鼠标悬停时显示的就是这段话；如果写在别处，它就只是个普通字符串
    global _client
    # 做什么：声明"下面我要修改的是**模块级**的那个 _client"
    # 逐词：
    #   global  【内置】"全局的"。它在告诉 Python：这个名字指的是文件最外层那个变量，
    #           不是函数里的临时变量
    #   _client 上面第 26 行定义的那个连接盒子
    # ⚠️ 这句是本函数最容易漏的一行：
    #    Python 有个规则 —— 只要函数里出现了"给某个变量赋值"，那个变量默认就是"局部变量"。
    #    所以不写 global，下面那句 _client = ... 只会造一个"出了函数就消失的临时变量"，
    #    而模块级那个 _client 永远是 None —— 结果每次调用都重新连一次库，懒加载完全失效

    if _client is None:
        # 做什么：判断"这个连接盒子还是空的吗"
        # 逐词：
        #   if          【内置】"如果" —— 条件判断的开头
        #   _client     【自起名】上面那个连接盒子
        #   is None     【内置】判断"是不是 None 本身"
        #               ⚠️ 这里必须用 is None，不要写 == None，也不要写 not _client
        #               原因：not _client 在"盒子是空的"和"盒子里装了个假值"时都为真，
        #               而 is None 只在"真的是 None"时为真 —— 精确得多
        #               另外 is 是"判断是不是同一个对象"，== 是"判断值相等"，null 值用 is 是惯例
        _client = chromadb.PersistentClient(path=CHROMA_DIR)
        # 做什么：真正去"打开/创建"这个向量库，把得到的客户端对象装进盒子
        # 逐词：
        #   _client               【自起名】盒子（左边 = 右边算出来的东西）
        #   chromadb              【三方库】上面 import 进来的包名
        #   .                     【内置】点号 = "调用它里面的东西"。
        #                         chromadb.PersistentClient 连起来读就是"chromadb 包里的 PersistentClient 这个类"
        #   PersistentClient      【三方库】chromadb 库里的一个类。拆开：
        #                         persistent（持久的）+ client（客户端）
        #                         → "数据写到磁盘、进程重启也还在"的客户端
        #                         它的兄弟是 EphemeralClient（ephemeral = 短暂的），那种是内存版，进程一退数据就没了
        #   (...)                 【内置】括号 = "调用"。对类来说，加括号 = "造一个实例出来"
        #   path=                 【三方库】keyword argument（关键字参数）= 用"参数名=值"的方式传参。
        #                         好处：不用记参数顺序，而且一眼能看出这个值是什么用途
        #   CHROMA_DIR            【本地】上面从 config/rag_conf.py 导进来的常量，
        #                         值是"项目根/rag_data"的**绝对路径**
        # 为什么要绝对路径：相对路径 "./rag_data" 是相对"当前工作目录"解析的，
        #   从 scripts/ 里跑一次索引就会在 scripts/ 下长出第二份库 —— 这个坑已经踩过
        # 持久化客户端：数据写到 rag_data/ 目录，服务重启数据还在

    return _client.get_or_create_collection(
        # 做什么：把"表对象"交出去（顺便保证这张表存在）
        # 逐词：
        #   return     【内置】"返回" —— 把值交给调用方，并且函数立刻结束
        #              ⚠️ 不加 return 的话函数会返回 None，调用方拿到的就是空
        #   _client    【自起名】盒子里的客户端对象
        #   .          【内置】点号 = 调用它里面的东西
        #   get_or_create_collection  【三方库】客户端对象身上的方法。拆开：
        #              get（拿）+ or（或者）+ create（创建）+ collection（集合）
        #              → "有这张表就拿给我，没有就新建一张"。名字本身就把行为说清了
        #              （同类还有 get_collection 只会拿、不存在就报错；create_collection 只会建、已存在就报错）
        #   (...)      【内置】调用它，里面传参数
        name=COLLECTION_NAME,
        # 逐词：
        #   name=           【三方库】这个方法的参数名，意思是"表叫什么名字"
        #   COLLECTION_NAME 【本地】常量，值 = "news_chunks"
        # 注意：名字里带 news_chunks 是"新闻 + 块"的意思 —— 改了这个常量，服务读的就是另一张空表了
        metadata={"hnsw:space": "cosine"},
        # 做什么：告诉这张表"用哪种方式衡量两个向量的远近"
        # 逐词：
        #   metadata=  【三方库】参数名。meta（元、关于自身的）+ data（数据）→ "描述数据的数据"，
        #              也就是"关于这张表的附加设定"
        #   { ... }    【内置】花括号 = 字典（key: value 的键值对集合）
        #   "hnsw:space"  【第三方库的约定字符串】拆开：hnsw = Hierarchical Navigable Small World
        #              （分层的、可导航的小世界图）—— Chroma 内部用来做"快速找最近邻"的算法名；
        #              space = "空间"，指"在什么空间里量距离"。中间那个冒号是 Chroma 规定的书写格式
        #   "cosine"   【三方库的取值】余弦。cosine similarity 就是"余弦相似度"，
        #              它只看两个向量的**方向**是否一致、不看长度，最适合文本
        #              对比 "l2"（欧氏距离，看直线距离），那种对文本反而不太好用
    )
    # 【本地】COLLECTION_NAME 来自 config/rag_conf.py（值 = "news_chunks"）
    # metadata 里声明用余弦相似度（适合文本，只看方向不看长度）
    # 注意：这个方法每次调用都会"get_or_create"，所以第一次请求之后表就一直在了


