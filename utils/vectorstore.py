def search(vector: list, top_k: int) -> list:
    # 做什么：定义 search 函数，接收"一个向量"和"要几条"，返回命中的块
    # 逐词：
    #   search    【自起名】"搜索/检索"
    #   vector    【自起名】"向量"，也就是问题被向量化之后得到的那串数字
    #   top_k     【自起名】固定搭配：top（前几名）+ k（个数）→ "取最像的前 k 条"
    #             k 是数学里表示"个数"的习惯字母，检索领域大家都这么叫
    #   : int     【内置】类型标注：top_k 应该是整数
    #   -> list   【内置】箭头后面是"返回值的类型标注"，说明这个函数返回一个列表
    """
    按向量检索最相近的块
    返回：[{"text": 块内容, "meta": 档案袋, "score": 相似度}, ...]（按相似度从高到低）
    """
    result = _collection().query(
        # 做什么：拿到表对象，调用 query 方法做"按向量找最像的"
        # 逐词：
        #   result =     【自起名】result（结果）—— 存一下返回值，下面要从里面取东西
        #   _collection()【本地】拿表对象
        #   .query       【三方库】集合对象的方法。query 原意"询问/查询"，
        #                在向量库里特指"按相似度查"（普通条件查询叫 get，见下面 get_hashes）
        query_embeddings=[vector],
        # 做什么：把要查的向量交进去
        # 逐词：
        #   query_embeddings=  【三方库】参数名（复数！）
        #   [vector]           【内置】方括号 = 列表。注意这里是"列表套着向量"，
        #                      也就是 [[0.12, -0.03, ...]]
        #   为什么要多套一层：这个接口支持"一次问多个问题"，所以要求外层是列表。
        #   我们只问一个，就套一层；取结果时也要对应多取一层 [0]（见下面三行）
        n_results=top_k,
        # 逐词：
        #   n_results=  【三方库】参数名。n（number 数量）+ results（结果）→ "要几条结果"
        #   值：top_k，它由调用方传进来（crud/rag.py 里传的是配置中的 TOP_K，默认 4）
    )
    # query_embeddings 要传"列表套向量"（它支持一次查多个问题），我们只查一个
    # 返回的是一个字典：{"ids": 列表套列表, "documents": …, "metadatas": …, "distances": …}

    texts = result["documents"][0]
    # 做什么：取出命中块的正文列表
    # 逐词：
    #   result        【自起名】上面 query 的返回值（一个字典）
    #   ["documents"] 【内置】字典取值：从字典里取出"键为 documents 的那一项"。
    #                 方括号里写键名 —— 这是字典和列表**共用的语法**，只差里面放的是"键"还是"下标"
    #   [0]           【内置】再取第 0 个元素。因为 documents 是"列表套列表"：
    #                 外层每个元素对应"一个问题的结果"，我们只问了 1 个 → 取第 0 个
    #                 ⚠️ 下标从 0 开始数，不是从 1
    metas = result["metadatas"][0]
    # 做什么：取出命中块的档案袋列表（第 i 个档案袋描述第 i 块内容）
    # 逐词：
    #   metas         【自起名】metadata 的复数缩写（这里为了短一点）
    #   ["metadatas"] 【三方库】键名（复数）
    distances = result["distances"][0]
    # 做什么：取出命中块的"距离"列表
    # 逐词：
    #   distances   【自起名】distance（距离）的复数
    #   ⚠️ 注意它给的是**距离**（越小越像），不是相似度（越大越像）—— 下一步要换算
    # query 返回的是"列表套列表"，所以每项都取第 0 个

    hits = []
    # 做什么：准备一个空列表，用来装"整理好格式的命中结果"
    # 逐词：
    #   hits  【自起名】hit（命中）+ s（复数）→ "命中的那些条目"
    #   []    【内置】空列表的写法（对比：空字典是 {}、空集合是 set()）
    for i in range(len(texts)):
        # 做什么：用下标遍历，好同时取 texts / metas / distances 三个列表的同一位置
        # 逐词：
        #   for ... in ...  【内置】"遍历"循环：把右边那个东西里的元素一个接一个取出来
        #   i               【自起名】循环变量，装的是"第几轮"（0, 1, 2 …）
        #   range(...)      【内置】生成一串整数。这里生成 0 到 n-1
        #   len(texts)      【内置】len = length 的缩写 → "长度"，返回列表里有多少个元素
        #   ⚠️ 为什么不直接 for text in texts：因为我们还要取 metas[i]、distances[i]，
        #      有下标才能把三个列表"对齐"
        hits.append({
            # 做什么：往 hits 列表末尾追加一个字典（一块命中结果的完整描述）
            # 逐词：
            #   hits    【自起名】上面那个空列表
            #   .append 【内置】列表的方法：往**末尾追加一个元素**（一次加一个）
            #           ⚠️ 别和 .extend 搞混：extend 是"把另一个列表里的元素逐个并进来"；
            #              append 加的是"一个东西"，哪怕那个东西本身是个列表（会变成嵌套）
            #   (       【内置】方法调用的括号
            #   { ... } 【内置】花括号 = 字典，也就是"键值对"
            "text": texts[i],
            # 逐词：
            #   "text"     【自起名】我们自己定的键名（Chroma 那边叫 documents，我们这里叫 text）
            #   texts[i]   【内置】取列表的第 i 个元素 —— 第 i 块的正文
            #   中间的冒号：字典里"键: 值"的分隔符
            "meta": metas[i],
            # 逐词：
            #   "meta"   【自起名】键名，存的是那一块的档案袋
            #   metas[i] 第 i 个档案袋（里面有 news_id / title / category / content_hash）
            "score": round(1 - distances[i], 4),
            # 做什么：把"距离"换算成"相似度"，并保留 4 位小数
            # 逐词：
            #   "score"      【自起名】键名，score（分数）→ 这里存的是相似度
            #   round(A, 4)  【内置】round = "四舍五入"到指定小数位。
            #                第一个参数是数字，第二个是要保留几位（4 = 保留 4 位小数）
            #   1 - distances[i]  【内置】减法。为什么要"1 减去它"：
            #                距离 0 表示"完全一样" → 相似度要是 1；
            #                距离越大越不像 → 相似度越小。所以 相似度 = 1 - 距离
            #   ⚠️ 这一步最容易写反：写成 distances[i] 的话，最像的会排到最后，
            #      而且**不会报错**，是那种最难查的"静默错误"
        })

    hits.sort(key=lambda x: x["score"], reverse=True)
    # 做什么：把 hits 按相似度从大到小排序
    # 逐词：
    #   hits        【自起名】上面装好的列表
    #   .sort()     【内置】列表方法：**原地排序**（直接改这个列表本身，没有返回值）。
    #               ⚠️ 所以千万别写 hits = hits.sort()，那样会把列表变成 None
    #               （想要"排好序的新列表、不动原列表"，用 sorted(hits, ...)）
    #   key=        【内置】排序参数：告诉 sort "按什么排序"。
    #               它会拿 key 算出来的值来比大小（比较的不是元素本身，而是元素的某个字段）
    #   lambda x: x["score"]  【内置】lambda = "一次性小函数"，写法是 lambda 参数: 结果。
    #               这句等价于：
    #                   def 某个名字(x):
    #                       return x["score"]
    #               意思是"给我一个命中项，我返回它的 score 字段"
    #   reverse=True 【内置】True = 反着排（从大到小）。默认是 False（从小到大）
    # 换成相似度之后再排序，保证"最相关的排最前面"

    return hits
    # 做什么：把排好序的命中列表交出去
    # 逐词：
    #   return  【内置】返回
    #   hits    装着一堆 {text, meta, score} 的列表
    # 调用方：【本地】crud/rag.py 里 retrieve() 函数中的 vectorstore.search(...)


# ------------------------------------------------------------
# 第五部分：取指纹（get_hashes）—— 增量索引的依据
# ------------------------------------------------------------


def get_hashes() -> dict:
    # 做什么：定义函数，返回一个"新闻id → 内容指纹"的字典
    # 逐词：
    #   get_hashes  【自起名】get（取）+ hashes（哈希值/指纹，复数）
    #               hash 原意是"剁碎、杂烩"，在计算机里指"把任意内容压成固定长度的指纹"
    #   -> dict     【内置】类型标注：说明返回一个字典
    """
    取出已入库新闻的内容指纹：{news_id: 内容指纹}
    用途：建索引时比对哪些新闻变了、哪些没变（这就是"增量索引"的依据）
    """
    data = _collection().get(include=["metadatas"])
    # 做什么：把库里所有块的"档案袋"取出来（不取正文和向量，快很多）
    # 逐词：
    #   data          【自起名】随便起的名字，装返回值
    #   .get()        【三方库】集合对象的方法：按条件"把数据取出来（普通查询）"。
    #                 ⚠️ 和 .query() 区分：
    #                     query = 按【相似度】找 → 用于"用户问了个问题"
    #                     get   = 按【条件/全部】取 → 用于"我要遍历所有数据"
    #   include=      【三方库】参数名："我要结果里包含哪些字段"。
    #                 不传的话默认不带 metadatas，就一定取不到我们要的指纹
    #   ["metadatas"] 【三方库】要求的取值列表。只写 metadatas = 只要档案袋，
    #                 不要 documents（正文）和 embeddings（向量）—— 省时间也省内存
    # 注意：这里没有传 where= 条件 → 等于"全表取"，不过只取档案袋所以不重

    hashes = {}
    # 做什么：准备一个空字典
    # 逐词：
    #   hashes  【自起名】上面函数名里也用了这个词
    #   {}      【内置】空字典的写法（⚠️ 空列表是 []、空集合是 set()，别记混）
    for meta in data["metadatas"]:
        # 做什么：挨个取出每一块的档案袋
        # 逐词：
        #   for meta in ...  【内置】遍历。这里 meta 每轮就是一个字典（一块的档案袋）
        #   data             【自起名】上面取到的结果（是个字典）
        #   ["metadatas"]    【内置】字典取值，拿到"所有档案袋"的列表
        if meta and "news_id" in meta:
            # 做什么：跳过"空的档案袋"和"没有 news_id 的块"
            # 逐词：
            #   if ... and ...  【内置】and = "并且"，两个条件都为真才进这个分支
            #   meta            【内置】非空字典本身就是"真值"；如果它是 None 或空字典，
            #                   这里就是假 → 相当于"先确认档案袋不是空的"
            #   "news_id" in meta  【内置】in 用在字典上时，判断的是"这个**键**在不在字典里"
            #                   （不是"值在不在"，这点很容易记错）
            hashes[meta["news_id"]] = meta.get("content_hash", "")
            # 做什么：把"新闻 id → 内容指纹"记进结果字典
            # 逐词：
            #   hashes[...] =      【内置】字典赋值：左边是"取哪个键"，右边是要存的值。
            #                      键不存在就是新增，存在就是覆盖
            #   meta["news_id"]    【内置】取出档案袋里 news_id 的值（会当成新字典的键）
            #   meta.get("content_hash", "")  【内置】字典的 .get(键, 默认值)：
            #                      有 content_hash 这个键就返回它的值；
            #                      没有就返回第二个参数（这里是空字符串 ""），**不会报错**
            #                      ⚠️ 对比 meta["content_hash"]：键不存在时会直接 KeyError 崩掉。
            #                         这里必须用 .get，因为老数据可能没这个字段
            #                      ⚠️ 默认值为什么给 "" 而不是 None：Chroma 的元数据不允许 None
            #                         （实测会 TypeError），所以只能给空串
    # 只认带 news_id 的块（别的来源若没有这个字段，会被这一行自动跳过）

    return hashes
    # 做什么：返回 {新闻id: 内容指纹} 这个字典
    # 调用方：【本地】crud/rag.py 里 build_index() 中的 old_hashes = ...
    # 用途：建索引时拿它和现在算出来的指纹对比 —— 一样就跳过（这就是"增量索引"省时间的原理）


