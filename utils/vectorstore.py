def count() -> int:
    # 做什么：定义函数，返回库里现在有多少块
    # 逐词：
    #   count  【自起名】"数数"；-> int 说明返回整数
    """返回库里现在有多少块（给统计接口用）"""
    return _collection().count()
    # 做什么：拿到表对象，调它的 count()，把结果直接返回
    # 逐词：
    #   return          【内置】返回
    #   _collection()   【本地】拿表对象
    #   .count()        【三方库】集合对象的"计数"方法 —— 它只数个数，
    #                   不会把数据取出来，所以非常快
    #   ⚠️ 注意这里有**两个 count**，不是一个：
    #       前面那个 count 是本文件定义的函数名（【自起名】）
    #       后面那个 .count() 是 chromadb 提供的方法（【三方库】）
    #       同名但是两回事 —— 这种"重名"最容易看晕
    # 调用方：【本地】routers/ragchat.py 的 /api/rag/stats 接口、scripts/ingest_news.py 打印统计
