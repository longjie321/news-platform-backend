from config.rag_conf import CHUNK_SIZE, CHUNK_OVERLAP, CHUNK_SEPARATORS
# 做什么：从配置中心取出切块要用到的三个常量
# 逐词：
#   from       【内置】固定搭配 from A import B = "从 A 里取出 B"
#   config     【本地】项目里的 config 包
#   .rag_conf  【本地】config 包里的 rag_conf.py
#   import     【内置】"取出"
#   CHUNK_SIZE       【本地】每块最多多少个字（值 400）
#   CHUNK_OVERLAP    【本地】相邻块重叠多少个字（值 50）
#   CHUNK_SEPARATORS 【本地】分隔符优先级列表
#                     （值是 ["\n\n", "\n", "。", "！", "？", ".", "!", "?", " ", ""]）
#   逗号：一次取多个名字时用逗号隔开
# 为什么放配置里：切块参数属于"可调项"，改效果时只动 config，不用翻这个文件
# 切块三件套：块大小、重叠长度、分隔符优先级（都在配置中心里）

# ------------------------------------------------------------
# 主函数：split_text
# ------------------------------------------------------------


def split_text(text: str,
               chunk_size: int = CHUNK_SIZE,
               chunk_overlap: int = CHUNK_OVERLAP,
               separators: list = None) -> list:
    # 做什么：定义函数 split_text，接收原文和三个可选参数，返回切好的块列表
    # 逐词：
    #   def           【内置】define（定义）+ 函数名 → "定义函数"的关键字
    #   split_text    【自起名】split（切分）+ text（文本）→ "切文本"。这不是任何库的 API
    #   text: str     【自起名 + 内置】text 是参数名；: str 是类型标注（说明该传字符串）
    #   chunk_size: int = CHUNK_SIZE
    #        → chunk_size 【自起名】"块的大小"；
    #          : int      【内置】说明该传整数；
    #          = CHUNK_SIZE  【内置】**默认参数**：调用时不传就用这个值（配置里的 400）
    #   chunk_overlap: int = CHUNK_OVERLAP
    #        → 【自起名 + 内置】"块之间重叠多少"，默认取配置里的 50
    #   separators: list = None
    #        → separators 【自起名】"分隔符们"，默认值是 None（也就是"没传"）
    #          ⚠️ 为什么默认值写 None，而不是直接写 = CHUNK_SEPARATORS？
    #             这里有个经典坑：函数的默认值只在"定义函数的那一瞬间"算一次，
    #             而且所有调用共用同一个对象。如果默认值是列表、
    #             函数里又不小心改了这个列表，那改动会**被后面的调用继承**（非常难查）。
    #             所以惯例是：默认写 None，进函数后再判断"是 None 就用真正的默认值"
    #   -> list       【内置】返回类型标注：返回一个列表
    #   括号换行写：Python 允许在**括号没闭合**时换行，这样参数多时好读
    #   :             【内置】冒号 = 下面缩进的都是函数体
    """
    把一段长文本切成若干小块，返回块列表
    text：要切的原文
    chunk_size：每块最大字符数
    chunk_overlap：相邻块重叠字符数
    separators：分隔符优先级（不传就用配置里的默认值）
    """
    if separators is None:
        # 做什么：判断"调用方到底传了分隔符没有"
        # 逐词：
        #   if              【内置】"如果"
        #   separators      【自起名】上面那个参数
        #   is None         【内置】判断"是不是 None 本身"
        #                   ⚠️ 这里**必须**用 is None，不能写 if not separators：
        #                      因为空列表 [] 也是"假值"，但"传了个空列表"和"没传"
        #                      是两种不同的意图 —— 用 not 会把它们混为一谈。
        #                      （is 是"是不是同一个对象"；== 是"值相等"；判断 None 用 is 是惯例）
        separators = CHUNK_SEPARATORS
        # 做什么：没传就用配置里的默认分隔符列表
        # 逐词：
        #   separators        【自起名】左边重新赋值给同一个参数名（覆盖掉那个 None）
        #   =                 【内置】赋值（判断相等是两个等号 ==）
        #   CHUNK_SEPARATORS  【本地】上面 import 进来的常量
        # 没传分隔符就用配置中心的默认优先级

    text = (text or "").strip()
    # 做什么：把参数清洗成"干净字符串"，防止传进来 None 或纯空白
    # 逐词：
    #   text           【自起名】把清洗结果重新赋给 text（覆盖原值，下面都用清洗过的）
    #   (text or "")   【内置】or 的用法：左边是"假值"就取右边。
    #                  所以 text 是 None 或空串时，这里得到 ""
    #                  → 目的：保证后面 .strip() 能安全调用（对 None 调 .strip() 会 AttributeError 崩掉）
    #   .strip()       【内置】字符串方法：去掉**首尾**的空白（空格、换行、制表符）。
    #                  ⚠️ 只去首尾，中间的空白不动 —— 它不会把 "a b" 变成 "ab"
    #   外层那对小括号没有语法作用，只是把 or 和 strip 的关系标清楚，好读
    # 防止传进来 None 或纯空白，先统一处理成干净字符串

    if not text:
        # 做什么：判断"清洗完是不是空的"
        # 逐词：
        #   not   【内置】"取反"。空字符串在条件判断里等于"假"，所以 not text 就是"它是空的"
        #   ⚠️ 这正是 None 和 "" 的"共同点"：它们放进 if 判断时行为一样。
        #      所以当你要区分这两个时，就不能用 not，得用 is None（上面那句就是例子）
        return []
        # 做什么：返回一个空列表
        # 逐词：
        #   return  【内置】返回 —— 函数到此结束，下面全都不执行（这叫"提前返回"）
        #   []      【内置】空列表（对比：空字典是 {}、空集合是 set()）
    # 空文本没有可切的东西，直接返回空列表
    # 注意：返回的是"空列表"而不是 None —— 因为调用方（crud/rag.py）会写
    #   split_text(...) or [news.title]，空列表是假值所以会触发它的兜底逻辑

    if len(text) <= chunk_size:
        # 做什么：判断"这段文本本来就够短吗"
        # 逐词：
        #   len(text)   【内置】len = length（长度）→ 返回字符串里有多少个**字符**。
        #               ⚠️ 是字符数不是字节数：中文一个字算 1 个字符
        #   <=          【内置】小于等于（注意"小于"在前、"等于"在后，别写成 =<）
        #   chunk_size  【自起名】上面那个参数（默认 400）
        return [text]
        # 做什么：把整段文本装进一个列表后返回
        # 逐词：
        #   [text]  【内置】方括号 = 列表，里面放着 text。
        #           ⚠️ 为什么不直接 return text：
        #              函数的约定是"永远返回列表"，这样调用方不用判断
        #              "回来的到底是字符串还是列表"，可以统一按列表处理
    # 文本本来就够短：不用切，整个就是一块
    # ⚠️ 本项目实测：403 篇新闻最长只有 192 字，全部走了这个分支 ——
    #    所以下面那一大段"递归切块 + 重叠"的代码在真实数据上一次都没执行过。
    #    面试时不要主动吹"切块与重叠策略"，被问到就说"语料偏短，一篇一块；
    #    切块器是按长文档写的，为以后接入长正文留的"

    # ---------- 第 1 步：选出这一级要用的分隔符 ----------
    sep_index = len(separators) - 1
    # 做什么：先假设"一个分隔符都用不上"，把候选下标指向最后一个
    # 逐词：
    #   sep_index   【自起名】separator（分隔符）+ index（下标）→ "用第几个分隔符"
    #   =           【内置】赋值
    #   len(separators)  【内置】数一数分隔符列表有几个元素（本项目是 10 个）
    #   - 1         【内置】减 1。
    #               ⚠️ 为什么要减 1：Python 的下标**从 0 开始**数，
    #                  10 个元素的下标是 0~9，最后一个就是 长度-1
    # 为什么先设成"最后一个"：分隔符列表最后一个元素是空字符串 ""，
    #   它的含义是"没有符号可用了，只能按字数硬切" —— 正好当兜底
    for i, sep in enumerate(separators):
        # 做什么：从前往后挨个检查分隔符，看哪个真的能用
        # 逐词：
        #   for ... in ...      【内置】遍历循环
        #   enumerate(列表)     【内置】"枚举"：它把列表变成"（下标, 元素）"一对一对地给出来。
        #                       ⚠️ 为什么不用普通 for sep in separators：
        #                          因为下面要记录"是第几个"（sep_index = i），
        #                          所以必须同时拿到下标。
        #                          这比"自己写 i = 0，每轮 i += 1"干净得多
        #   i     【自起名】下标（0, 1, 2 …）
        #   sep   【自起名】这一轮的分隔符（是个字符串）
        if sep and sep in text:
            # 做什么：判断"这个分隔符非空，而且真的出现在文本里"
            # 逐词：
            #   sep and ...   【内置】and = "并且"，两个条件都成立才进分支。
            #                 前半段 sep 单独放着 = "sep 这个字符串不能是空的"，
            #                 因为空字符串在条件里是假值 ——
            #                 它对应的正是最后那个"硬切"兜底项，那个不能在这里被选中
            #   sep in text   【内置】in 用在字符串上 = "这段子串在不在 text 里"（子串判断）。
            #                 ⚠️ 不是"相等"判断
            sep_index = i
            # 做什么：记下这个能用的分隔符的下标
            # 逐词：sep_index 【自起名】第几个；= i 【内置】赋值
            break
            # 做什么：立刻跳出这个 for 循环
            # 逐词：
            #   break  【内置】"中断" —— 结束**整个**循环。
            #          ⚠️ 和 continue 的区别：continue 只是"跳过这一轮、继续下一轮"；
            #             break 是"整个循环不做了"。
            #          这里要的是"找到第一个能用的就停"，所以用 break
    # 从左到右找第一个"文本里真的存在"的分隔符
    # 一个都找不到时，sep_index 停在最后一个（空字符串 ""，代表硬切）

    separator = separators[sep_index] if separators else ""
    # 做什么：把选中的分隔符取出来；万一列表是空的，就用空字符串兜底
    # 逐词：
    #   separator           【自起名】最终选定的分隔符（单数！和上面复数的 separators 区分开）
    #   separators[sep_index]  【内置】按下标取列表里的元素
    #   A if 条件 else B    【内置】"三元表达式"：条件成立取 A，否则取 B
    #   if separators       【内置】判断"列表非空"（非空列表是真值）
    #   为什么要这个保险：递归调用时会把"用过的分隔符"丢掉
    #     （见下面 separators[sep_index + 1:]），真丢到最后会变成空列表，
    #     那时用 [] [0] 取下标会直接 IndexError 崩掉
    # separators 可能在上层递归中已经被用光了，防空列表报错

    # ---------- 第 2 步：按分隔符把文本拆开 ----------
    if separator:
        # 做什么：判断"有没有真分隔符可用"
        # 逐词：
        #   if separator  【内置】空字符串是假值 → 所以这句等于"separator 不是空的"
        pieces = text.split(separator)
        # 做什么：按这个分隔符把文本切成一串碎片
        # 逐词：
        #   pieces      【自起名】piece（碎片）+ s → "切出来的碎片们"
        #   text        【自起名】上面清洗过的原文
        #   .split(x)   【内置】字符串方法：按 x 把字符串切成一个**列表**。
        #       例："a。b。".split("。") → ['a', 'b', '']
        #       ⚠️ 注意两件事：
        #          ① 分隔符本身会被**吃掉**（不在结果里）
        #          ② 如果原文以分隔符结尾，末尾会多出一个空字符串 ''
        pieces = [p + separator for p in pieces[:-1]] + [pieces[-1]]
        # 做什么：把被吃掉的分隔符"拼回每一段的末尾"
        # 逐词：
        #   pieces[:-1]   【内置】这是**切片**：从头取到"倒数第一个之前"，
        #                 也就是"去掉最后一个元素"。
        #                 ⚠️ 切片写法 [起点:终点]，终点那一个**取不到**；
        #                    省略起点 = 从头开始
        #   里面的 p     【自起名】列表推导式的循环变量，每轮是一个碎片
        #   p + separator 【内置】字符串相加 = 拼接（把分隔符接在碎片后面）
        #   [ ... for p in pieces[:-1]]
        #                 【内置】这就是"**列表推导式**"：把右边每个元素加工一下，组成新列表。
        #                 等价于：临时 = []; for p in pieces[:-1]: 临时.append(p + separator)
        #   [pieces[-1]]  【内置】负数下标：-1 表示"最后一个元素"。
        #                 最后一个碎片后面没有分隔符（它本来就空），所以原样保留
        #   +             【内置】两个列表相加 = 合并成一个新列表
        # 把分隔符拼回每一段的末尾
        #   比如"今天很热。明天降温。"按句号切完是["今天很热","明天降温",""]
        #   拼回去变成["今天很热。","明天降温。",""]，保住标点，语义才完整
        #   为什么要保住标点：标点是句子语义的一部分，缺了它向量算出来会偏，检索会变差
    else:
        # 做什么：没有可用分隔符时的兜底 —— 按固定长度硬切
        # 逐词：
        #   else  【内置】"否则"（和上面的 if separator: 配对）
        pieces = [text[i:i + chunk_size] for i in range(0, len(text), chunk_size)]
        # 逐词：
        #   range(起点, 终点, 步长)  【内置】生成一串整数。
        #       这里起点 0、终点 len(text)、步长 chunk_size
        #       → 生成 0, 400, 800, 1200 …（终点本身取不到，所以不会越界）
        #   text[i:i + chunk_size]  【内置】切片：取从下标 i 到 i+400 的**一段**，
        #       含 i、不含 i+400（所以正好 400 个字符）
        #   [ ... for i in range(...) ]  【内置】列表推导式：把每个 i 对应的那一段收集起来
        # 空分隔符 = 没有任何符号可用：直接按 chunk_size 等长硬切
        # 这就是配置里 CHUNK_SEPARATORS 最后那个 "" 的用途

    # ---------- 第 3 步：把碎段拼成大小合适的块 ----------
    chunks = []
    # 做什么：准备一个空列表，装最终的"块"
    # 逐词：
    #   chunks  【自起名】chunk（块）+ s → "切好的块们"
    #   []      【内置】空列表
    current = ""
    # 做什么：准备一个空字符串，当作"正在积攒的当前块"
    # 逐词：
    #   current  【自起名】"当前的" —— 正在往里面塞碎片的那个临时块
    #   = ""     【内置】空字符串（⚠️ 不是 None：下面要往它上面 += 字符串，
    #             None 不能做字符串相加，会 TypeError）
    # 这个变量是"攒够了就收工、收工后清空再来"的思路，变量名叫 current 很贴切

    for piece in pieces:
        # 做什么：挨个处理每个碎片
        # 逐词：
        #   for ... in pieces  【内置】遍历
        #   piece              【自起名】这一轮拿到的碎片
        if len(piece) > chunk_size:
            # 做什么：这一小段自己就超长了（说明上一级的分隔符都不够用）
            # 逐词：
            #   len(piece)    【内置】这个碎片有几个字符
            #   >             【内置】大于。
            #                 ⚠️ 注意是"严格大于"：正好等于 chunk_size 的块是合法的，不用再切
            #   chunk_size    【自起名】每块上限
            if current:
                # 做什么：先把手里攒着的块"收工"存进 chunks
                # 逐词：
                #   if current  【内置】非空字符串是真值 → 这句等于"current 里有东西"
                #               为什么必须先收工：接下来要用递归处理这个超长碎片，
                #               如果手里的 current 留着，后面拼块的顺序就乱了
                chunks.append(current)
                # 做什么：把当前块加进结果列表
                # 逐词：
                #   chunks        【自起名】结果列表
                #   .append(x)    【内置】列表方法：往**末尾追加一个元素**（一次加一个）。
                #                 ⚠️ 和 .extend 的区别见下面
                #   current       【自起名】里面攒好的那一块文字
                current = ""
                # 做什么：清空，准备重新攒
                # 逐词：current 【自起名】；= "" 【内置】赋成空字符串
            chunks.extend(
                # 做什么：把这个超长碎片递归切出来的结果，**逐个**并进 chunks
                # 逐词：
                #   .extend(某个列表)  【内置】把参数列表里的元素**逐个**加进来。
                #         ⚠️ 和 append 的关键区别：
                #              chunks.append([a, b])  → 结果是 [..., [a, b]]（嵌套了一个列表）
                #              chunks.extend([a, b])  → 结果是 [..., a, b]（正确摊平）
                #           这里要的是"摊平"，所以必须用 extend
                split_text(piece, chunk_size, chunk_overlap, separators[sep_index + 1:])
                # 做什么：递归调用 split_text 自己，把这段超长碎片再切一次
                # 逐词：
                #   split_text     【本地】本文件这个函数自己（递归调用）。
                #                  ⚠️ 递归 = 函数调用自己。它必须有个"会终止"的保证，见下面
                #   piece          【自起名】那个超长的碎片
                #   chunk_size / chunk_overlap  【自起名】原样传下去（规则不变）
                #   separators[sep_index + 1:]  【内置】切片：从"下一个分隔符"取到结尾。
                #         sep_index 是刚才这一级选中的分隔符下标，+1 就是它的下一个；
                #         冒号后面空着 = "一直取到最后"。
                #         → 效果：把已经用过的分隔符丢掉，换低一级的再切
                #           （段落切不动 → 换换行 → 再不行换句号 → …）
                #         ⚠️ 这就是**递归能终止**的关键：
                #            分隔符列表每递归一层就短一截，最后会变成空列表，
                #            那时 separator 是 ""，代码走"按字数硬切"那个分支，
                #            而硬切出来的每段一定 ≤ chunk_size，就不会再递归了
            )
            # 递归：换"下一级"分隔符再切这一段（段落不行换换行，换行不行换句号……）
            # separators[sep_index + 1:]：把已经用过的分隔符丢掉，避免无限递归
        elif len(current) + len(piece) <= chunk_size:
            # 做什么：如果"当前块 + 这个碎片"还装得下，就继续往里塞
            # 逐词：
            #   elif  【内置】else if 的缩写："否则如果…"。
            #         意思是"上面的 if 不成立，再看这个条件"
            #   len(current) + len(piece)  【内置】两个长度相加 = 合并后的总长度
            #   <= chunk_size              【内置】不超过上限
            current += piece
            # 做什么：把碎片接到当前块末尾
            # 逐词：
            #   +=  【内置】复合赋值：current += piece 等价于 current = current + piece。
            #        ⚠️ 字符串没有 .append 方法，拼接就是用 + 或 +=
            # 装得下：继续往当前块里攒
        else:
            # 做什么：装不下了 → 当前块收工，这个碎片开一个新块
            # 逐词：else 【内置】"否则"（上面两个条件都不成立）
            chunks.append(current)
            # 做什么：把攒好的当前块存进结果
            # 逐词：.append 【内置】追加一个元素；current 【自起名】攒好的那一块
            current = piece
            # 做什么：让"当前块"从这一块碎片重新开始
            # 逐词：
            #   current   【自起名】被重新赋值
            #   = piece   【自起名】⚠️ 是赋值（一个等号），不是比较。
            #             意思"从这一块开始新的积攒"
            # 装不下了：当前块收工，这一段开新块

    if current:
        # 做什么：循环结束后，手里可能还攒着最后一块，别漏了
        # 逐词：
        #   if current  【内置】非空字符串为真 → "还有剩的就别丢"
        #   ⚠️ 这是一个特别容易漏的地方：如果循环最后一次是走"继续往 current 里攒"，
        #      那一块还躺在 current 里、没进 chunks —— 漏了它就少一块内容
        chunks.append(current)
        # 逐词：chunks 【自起名】结果列表；.append 【内置】追加；current 【自起名】最后攒的那块
    # 循环结束时手里可能还攒着最后一块，别漏了

    # ---------- 第 4 步：给相邻块加重叠 ----------
    if chunk_overlap > 0 and len(chunks) > 1:
        # 做什么：判断"需不需要加重叠"（重叠数 > 0 且至少有两块）
        # 逐词：
        #   chunk_overlap  【自起名】要重叠的字符数（配置里是 50）
        #   > 0            【内置】大于 0 → 说明"需要重叠"（配 0 就是不重叠）
        #   and            【内置】"并且"，两个条件都为真才进分支
        #   len(chunks) > 1  【内置】至少 2 块才谈得上"相邻"（1 块没有前一块可借）
        with_overlap = [chunks[0]]
        # 做什么：新建一个列表，先把第 0 块放进去（第一块前面没有块，不用加重叠）
        # 逐词：
        #   with_overlap       【自起名】with（带着）+ overlap（重叠）→ "加过重叠之后的新列表"
        #   = [chunks[0]]      【内置】方括号建一个列表，里面放"第 0 块"。
        #                      chunks[0] 是按下标取第 0 个元素（下标从 0 开始）
        #   ⚠️ 为什么要新建一个列表而不是改原列表：
        #      遍历一个列表的同时往里面追加元素，长度会一直变、行为会错乱。
        #      所以先建一个新的，最后再整体替换（见下面 chunks = with_overlap）
        for i in range(1, len(chunks)):
            # 做什么：从第 1 块开始遍历（第 0 块上面已经处理过了）
            # 逐词：
            #   range(1, len(chunks))  【内置】生成 1, 2, 3 … 直到 len-1。
            #                          起点写 1 表示"跳过第 0 块"
            #   i                      【自起名】当前块的下标
            with_overlap.append(chunks[i - 1][-chunk_overlap:] + chunks[i])
            # 做什么：把"前一块的尾巴 + 当前块"拼起来，作为新的当前块
            # 逐词：
            #   with_overlap  【自起名】上面的新列表
            #   .append(...)  【内置】追加一个元素（这里追加的是一个字符串）
            #   chunks[i - 1] 【内置】前一块（当前下标减 1）。
            #                 ⚠️ 因为起点是 1，所以 i-1 最小是 0，不会变成负数
            #   [-chunk_overlap:]  【内置】又是切片，而且用了**负数下标**：
            #       负号表示"从后往前数"，所以 [-50:] = "取最后 50 个字符"。
            #       ⚠️ 两个细节：
            #          ① 如果这一块不足 50 个字符，切片会**自动只给现有的**（不报错）
            #          ② 冒号后面的空 = "一直到结尾"，所以这是"从倒数第 50 个开始，取到末尾"
            #   +                【内置】字符串拼接：前一块的尾巴 接上 当前块
            # 效果：当前块开头多了"前一块的最后 50 个字"
            # 为什么要这样：万一一句话正好被切在边界上，
            #   下一块里也能看到这句话的开头，语义不会断
        chunks = with_overlap
        # 做什么：用加过重叠的新列表，替换掉原来的列表
        # 逐词：
        #   chunks        【自起名】原来的变量名（被重新赋值为新列表）
        #   = with_overlap【自起名】上面那个新列表
        #   ⚠️ 变量名可以被重复使用来"接住新结果"，这是常见写法；
        #      但要清楚"现在 chunks 指向的是新列表，旧列表已经没人用了"
        # 用新列表替换旧列表（变量名复用是允许的）

    return [c.strip() for c in chunks if c.strip()]
    # 做什么：去掉每块首尾的空白、丢掉去完变空的块，然后返回
    # 逐词（整个表达式由外往内读）：
    #   return          【内置】返回
    #   [ ... for c in chunks ... ]  【内置】列表推导式（带筛选条件的版本），
    #                   把 chunks 里满足条件的元素加工后组成新列表
    #   c               【自起名】循环变量，每轮是一块文字
    #   c.strip()       【内置】去掉这一块首尾的空白
    #                   为什么每块都要 strip：
    #                     硬切和递归拼接过程中会引入多余空格/换行，
    #                     留着会让向量里混进噪声，也会让去重比对不准
    #   if c.strip()    【内置】筛选条件：去掉空白后**非空**才保留。
    #                   ⚠️ 这里为什么要判两次（一种是 if、一种是结果里再 strip 一次）：
    #                      如果块是 "   "（纯空格），strip 后是空字符串（假值），
    #                      这一块就该被丢掉 —— 空块进向量库没有任何意义，
    #                      还会占位置、干扰检索
    # 最后清洗一遍：去掉首尾空白，丢掉空块
