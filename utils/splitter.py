# 区域：文本切块器（自研，不用 LangChain）
# 作用：把一篇长新闻切成若干小块
#   为什么要切块：
#     ① 一整篇新闻太长，没法整个塞进给模型的提示词里
#     ② 检索是按"块"比对的，块越小越能精准命中某一段内容
#   切法叫"递归切块"：先按段落切，块还太大就换句号切，再不行就按字数硬切
#
# ============================================================
# 【学习版说明书】
# ============================================================
