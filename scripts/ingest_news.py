# 做什么：把"项目根目录"加进 Python 的模块搜索路径，让脚本从任何地方都能跑
# 逐词（由内向外读，像剥洋葱）：
#   __file__            【内置】Python 自动给的变量 = "当前这个脚本自己的路径"。
#                       名字两边的双下划线表示"这是 Python 内部的特殊变量"，不是我们起的
#   os.path             【标准库】os 模块里管路径的子模块。下面全是**函数**（要带括号）
#   .abspath(__file__)  【标准库】absolute path（绝对路径）
#                       → 把"可能是相对路径"换成"从盘符开始的完整路径"。
#                       为什么要转：相对路径依赖"当前工作目录"，不同地方跑结果不一样
#   .dirname(...)       【标准库】directory name（目录名）→ 取出"这个文件所在的文件夹"。
#                       套两层：第一层得到 scripts/，第二层得到项目根目录
#   sys.path            【标准库】一个**列表**，里面是 Python 找模块时会去翻的目录清单
#   .append(...)        【内置】列表方法：往末尾追加一个元素（这里追加的是"项目根目录"）
# 本文件 → 上一级(scripts) → 再上一级(项目根目录)
