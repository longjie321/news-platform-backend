# 区域：建索引脚本（离线脚本，不是接口）
# 作用：把 MySQL 里的新闻切块、向量化，存进向量库
#
# 什么时候要跑：
#   ① 第一次用 RAG 问答之前（必须跑，否则向量库是空的）
#   ② 新闻表有更新之后（再跑一遍就行，只会处理变化的部分）
#   ③ 换了向量模型之后（必须加 --rebuild 全量重建）
#
# 用法（在项目根目录执行）：
#   python scripts/ingest_news.py              增量：只处理新增和内容变化的新闻
#   python scripts/ingest_news.py --rebuild    全量重建：先清空向量库再全部重灌
#
# 关键理解（面试会问）：
#   ① 这个脚本能反复跑：靠"内容指纹比对 + upsert 幂等"两重保证
#   ② 为什么默认增量：向量化要调外部接口（花时间也花钱），
#      403 篇全量重算要几分钟，增量只要几秒
#   ③ 脚本要能从任意目录运行，所以下面把项目根目录塞进了 sys.path
#
# ============================================================
# 【学习版说明书】
# ============================================================
# 本文件是"逐词精讲版"。每行代码下面固定两段：
#   # 做什么：  一句话说清这行在干什么
#   # 逐词：    把这行里每个"词"拆开 —— 它是什么、从哪来、原意是什么
#
# 标签：【内置】不用 import ｜【标准库】自带模块要 import ｜【三方库】pip 装的
#       【本地】项目自己写的 ｜【自起名】只是自己起的名字，不是任何 API
