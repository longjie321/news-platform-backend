async def main():
    # 做什么：定义异步主函数，整个脚本的流程都写在这里
    # 逐词：
    #   async def  【内置】"定义协程函数"。
    #              加了 async 之后：① 调用它不会立刻执行，只得到"协程对象"；
    #              ② 必须用 await 或 asyncio.run 才会真的跑
    #   main       【自起名】约定俗成的入口函数名。
    #              ⚠️ 它不是 Python 的关键字，只是大家都这么叫（C/Java 里也有 main 的概念）
    #              括号空的 = 不接收参数
    parser = argparse.ArgumentParser(description="把 MySQL 新闻同步进向量库")
    # 做什么：创建一个"命令行参数解析器"
    # 逐词：
    #   parser  【自起名】"解析器"。因为下面要用它注册参数、再读参数，所以先存进一个名字
    #   =       【内置】赋值
    #   argparse      【标准库】上面 import 的模块
    #   .ArgumentParser  【标准库】模块里的类。拆开：Argument（参数）+ Parser（解析器）
    #                    → "参数解析器"。加括号 = 造一个实例出来
    #   description=  【标准库】参数名：这个工具是干什么的。
    #                 作用：用户敲 `python xxx.py --help` 时会显示这句话
    # Argparse 是【自起名】的变量（argparse 是模块名，Parser 是它里面的类）
    # description 只是 `--help` 时显示的说明文字

    parser.add_argument("--rebuild", action="store_true", help="全量重建（会先清空向量库）")
    # 做什么：往解析器里注册一个命令行开关 --rebuild
    # 逐词：
    #   parser          【自起名】上面那个解析器
    #   .add_argument(...)  【标准库】"添加参数"的方法。
    #                   ⚠️ 注意这里的 argument 是"命令行参数"的意思，和函数参数不是一回事
    #   "--rebuild"     【自起名参数名】两个减号开头 = 这是个"可选"开关（不是必填的位置参数）。
    #                   rebuild = re（重新）+ build（构建）
    #                   用户敲 --rebuild 就是"我要全量重建"
    #   action="store_true"  【标准库固定用法】拆开：
    #                   action（动作）+ store（存）+ true（真）
    #                   → "看到这个开关就存一个 True"。
    #                   效果：命令行**带** --rebuild → 值是 True；**不带** → 值是 False
    #                   ⚠️ 这是 argparse 规定的字符串取值（写死了几个选项），
    #                      写成 "store_true" 才对，别自己发明
    #   help="..."      【标准库】这个参数的说明文字，`--help` 时显示。
    #                   写清楚"会先清空向量库"很重要 —— 因为这是个**破坏性**操作，
    #                   用户得知道它会删数据
    # action="store_true"：命令行带这个开关就是 True，不带就是 False

    args = parser.parse_args()
    # 做什么：真正去读命令行，把结果装进一个对象
    # 逐词：
    #   args  【自起名】arguments（参数）的缩写
    #   parser          【自起名】上面那个解析器
    #   .parse_args()   【标准库】"解析参数"的方法：读 sys.argv（命令行输入），
    #                   按注册过的规则解析，返回一个**对象**
    #   ⚠️ 返回值不是一个字典，而是一个"命名空间对象"：所以后面要用
    #      args.rebuild（点号 + 属性名）来取值，不能写 args["rebuild"]
    #   属性名 = 开关去掉两个减号（--rebuild → .rebuild）
    # 之后用 args.rebuild 就能拿到 True / False（名字就是去掉两个减号后的 rebuild）

    before = count()
    # 做什么：先数一次向量库现在有多少块，记下来
    # 逐词：
    #   before   【自起名】"之前"
    #   count()  【本地】utils/vectorstore.py 的函数：内部调 chroma 的 .count()。
    #            ⚠️ 它不在 async def 里 await —— 因为 count() 是**同步**函数。
    #               这是个同步调用，会在主线程上执行（数据量小、很快，可以接受）。
    #               严格说也可以写成 await asyncio.to_thread(count)，但这里没必要
    # 为什么要记：最后打印"403 块 → 410 块"这样前后对比，一眼能看出这次跑了多少活
    # 记一下处理前的块数，方便对比

    async with AsyncSessionLocal() as db:
        # 做什么：开一个数据库会话，用完自动关
        # 逐词：
        #   async with ... as ...  【标准库语法】"异步上下文管理器"：
        #              进入时执行"准备动作"（这里是创建会话），
        #              离开时自动执行"收尾动作"（关闭会话）—— 不用自己写 close()
        #              ⚠️ 为什么前面要加 async：因为这个准备/收尾动作本身是异步的
        #   AsyncSessionLocal()  【本地】调用"会话工厂"，造出一个新的数据库会话
        #               ⚠️ 注意括号不能少：不带括号拿到的是"工厂"本身，不是会话
        #   db   【自起名】database 的缩写 → 这一次数据库对话的把手，下面查库都用它
        # 好处：就算中间抛异常，退出时也会帮你把会话关掉（不会漏连接）
        stats = await build_index(db, rebuild=args.rebuild)
        # 做什么：调用建索引函数，把结果统计存进 stats
        # 逐词：
        #   stats   【自起名】statistics（统计）的缩写，装返回的统计字典
        #   await   【内置】"等待" —— 等这个异步函数跑完再往下走。
        #           ⚠️ 没有 await：这行只是"创建了一个协程对象"，建索引根本不会执行，
        #              而且**不报错**（Python 只会在控制台偶尔给个 RuntimeWarning）
        #   build_index  【本地】crud/rag.py 的函数（上面 import 进来的）
        #   db           【自起名】上面那个会话，作为第一个位置参数传进去
        #   rebuild=args.rebuild  【内置】关键字参数：把命令行开关的值传进去。
        #               True = 全量重建（先清空）；False = 增量
        #   返回的字典有 6 项：total / added / updated / skipped / removed / chunks

    after = count()
    # 做什么：再数一次，看看处理完之后有多少块
    # 逐词：after 【自起名】"之后"；count() 【本地】同上面那句
    # 为什么在 async with 外面数：会话已经用完了，这里跟数据库无关，只查向量库
    mode = "全量重建" if args.rebuild else "增量索引"
    # 做什么：根据有没有 --rebuild，算出一个"给人看的模式名字"
    # 逐词：
    #   mode    【自起名】"模式"，装一个中文字符串
    #   =       【内置】赋值
    #   A if 条件 else B  【内置】"三元表达式"：条件成立取 A，否则取 B
    #   if args.rebuild   【自起名 + 内置】True 就取 "全量重建"
    #   else "增量索引"   否则取 "增量索引"
    # 为什么要这个变量：下面要打印出来告诉用户"这次到底是哪种模式"——
    #   不然用户看到"新增 0"会慌，其实他只是跑了一次增量
    print(f"索引构建完成（{mode}）：")
    # 做什么：往屏幕上打印一行结果标题
    # 逐词：
    #   print   【内置】输出到控制台
    #   f"..."  【内置】f-string：里面的 {mode} 会被替换成变量的值
    #   （）里的中文括号只是普通字符，没有语法含义
    print(f"  新闻总数：{stats['total']} 篇")
    # 做什么：打印新闻总数
    # 逐词：
    #   stats['total']  【内置】字典取值：取出键为 'total' 的那一项。
    #                   ⚠️ 注意是方括号 + **带引号**的键名 ——
    #                      因为键名是字符串，所以引号不能少（写 total 会被当成变量名去找）
    #                   ⚠️ 也正因为这个，如果 crud/rag.py 把返回字典的键改了名，
    #                      这里会直接 KeyError —— 这就是"接口约定"要小心改的原因
    #   开头那两个空格：纯格式，让输出看起来有层次
    print(f"  新增 {stats['added']} ｜ 更新 {stats['updated']} ｜ 未变跳过 {stats['skipped']} ｜ 清理 {stats['removed']}")
    # 做什么：一行打印四个统计数字（用全角竖线分隔，好看）
    # 逐词（这四项的含义，也是要能讲清的）：
    #   added   = 指纹表里没有的新闻（新入库）
    #   updated = 指纹变了，先删旧块再写新块的
    #   skipped = 指纹一样，跳过的（增量索引省下来的时间就在这）
    #   removed = MySQL 里已经删掉、向量库里还留着的"孤儿块"，被清理掉的
    #   ｜      【普通字符】全角竖线，只是分隔符，没有语法含义
    # 这四项的含义：
    #   added   = 指纹表里没有的新闻（新入库）
    #   updated = 指纹变了，先删旧块再写新块的
    #   skipped = 指纹一样，跳过的（增量索引省下来的时间就在这）
    #   removed = MySQL 里已经删掉、向量库里还留着的"孤儿块"，被清理掉的
    print(f"  本次写入 {stats['chunks']} 块")
    # 做什么：打印这次真正写进向量库的块数
    # 逐词：stats['chunks'] 【内置】取出键 chunks 的值（= 这次写入的块数）
    # 为什么它和"新闻总数"不是一回事：一篇新闻可能切出多块，
    #   而且没变化的新闻压根不写 —— 所以这个数通常远小于 403
    print(f"  向量库：{before} 块 → {after} 块")
    # 做什么：打印前后对比
    # 逐词：
    #   {before} / {after}  【自起名】上面那两次 count() 的结果
    #   →  只是个箭头字符，纯装饰
    # 这一行的用处：一眼看出"这次到底有没有写进去" ——
    #   如果是增量且一条都没变，两个数会相等，这是正常现象、不是失败

    await async_engine.dispose()
    # 做什么：关掉数据库连接池
    # 逐词：
    #   await             【内置】等它执行完（它本身是异步方法）
    #   async_engine      【本地】从 config/db_conf.py 导进来的引擎对象
    #   .dispose()        【三方库】SQLAlchemy 的方法。dispose = "处置、释放"
    #                     → 释放连接池里的所有连接、关闭引擎
    #   ⚠️ 为什么要显式关：脚本跑完进程退出时，如果连接没归还，
    #      SQLAlchemy 或数据库会打印警告（"连接被强制中断"之类）。
    #      显式 dispose 一下，退出得干干净净 —— 这是"脚本"和"服务"的区别：
    #      服务一直跑着，连接池要留着复用；脚本干完就该收摊
    # 关闭数据库连接池，让脚本干净退出（不关会有警告）

