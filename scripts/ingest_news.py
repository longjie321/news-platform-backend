from utils.vectorstore import count
# 做什么：从向量库封装里取出"计数"函数
# 逐词：
#   utils           【本地】项目里的工具包
#   .vectorstore    【本地】utils/vectorstore.py
#   count           【本地】那个文件里定义的函数（数一数向量库里有多少块）。
