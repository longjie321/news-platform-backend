if __name__ == "__main__":
    # 做什么：判断"这个文件是被**直接运行**的，还是被别处 import 的"
    # 逐词：
    #   if                【内置】"如果"
    #   __name__          【内置】Python 自动塞给每个模块的变量，表示"当前模块的名字"。
    #                     名字两边双下划线 = Python 内部特殊变量
    #   ==                【内置】判断相等（两个等号！一个等号是赋值）
    #   "__main__"        【内置约定值】字符串，注意是**带引号的**
    # 它的取值规则：
    #   直接运行本文件（python scripts/ingest_news.py）→ __name__ 就是 "__main__" → 条件成立
    #   被别处 import（import scripts.ingest_news）  → __name__ 是 "scripts.ingest_news" → 不成立
    # 所以这个守卫的意思是：**只有直接 run 这个脚本时才执行下面那行**
    # 好处：别处 import 本文件时，不会顺手把整个建索引流程跑起来
    #   （比如 pytest 收集测试文件时会 import 它们 —— 没有守卫的话副作用就发生了）
    asyncio.run(main())
    # 做什么：新建一个事件循环，把 main() 这个协程跑完，然后关掉循环
    # 逐词：
    #   asyncio     【标准库】上面 import 的异步框架
    #   .run(...)   【标准库】"跑" —— 它是"同步代码进入异步世界"的唯一入口：
    #               ① 建一个事件循环 ② 把协程挂上去执行 ③ 执行完关闭循环
    #   main()      【内置语法细节】注意**带括号**！括号 = "调用它"，得到的是"协程对象"。
    #               ⚠️ 如果不带括号写 asyncio.run(main)，传进去的是一个函数对象，
    #                  run 会报错（它要协程，不要函数）
    #   对比一下两种"带不带括号"（这俩正好相反，很容易记混）：
    #       asyncio.run(main())                    → 要括号（要协程对象）
    #       asyncio.to_thread(vectorstore.reset)   → 不要括号（要函数本身，让它在线程里调）
