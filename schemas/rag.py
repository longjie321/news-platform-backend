#
# 关键理解（面试会问）：
#   ① 校验放在这一层：不合法的请求在进业务代码之前就被拦掉，业务代码就不用到处判空
#   ② 参数一定要有上限（top_k 最大 10）：不限制的话有人传 100 就能把提示词塞爆
#   ③ 历史对话由前端传上来（不存数据库）：前端本来就存着消息列表，
#      再存一份数据库属于重复，代码也少一大截
