# ------------------------------------------------------------
# 导包（3 个 import，分别来自三个不同来源）
# ------------------------------------------------------------

from typing import List, Optional
# 做什么：从 typing 模块里取出 List 和 Optional 两个名字
# 逐词：
#   from      【内置】固定搭配 from A import B = "从 A 里取出 B"
#   typing    【标准库】Python 自带的"类型提示"工具包（不用 pip 装）。
#             type（类型）+ ing（表示"跟…有关的"）→ 跟类型有关的工具
#             ⚠️ 它的东西**只在写代码时有用**（给人看、给 IDE 检查、给 Pydantic 读），
#                Python 运行时并不会因为写了 List 就真的去检查是不是列表
#   import    【内置】"取出"
#   List      【标准库】"列表"这个类型的名字。List[X] 表示"一个列表，里面每一项都是 X"
#             ⚠️ 为什么要用 typing.List 而不是 Python 内置的 list：
#                这是旧写法（为了兼容老版本 Python）。现在也流行直接写 list[X]，
#                但项目里统一用了 typing 的写法，保持一致就行
#   Optional  【标准库】"可选的"。Optional[X] = "要么是 X，要么是 None"，
#             也就是"这个字段可以不给"
#   中间逗号：一次取多个名字要用逗号隔开

from pydantic import BaseModel, Field
# 做什么：从 pydantic 里取出 BaseModel 和 Field
# 逐词：
#   pydantic  【三方库】pip 装的校验库。名字来源于 "pedantic"（迂腐的、爱抠细节的），
#              改拼成 py 开头（Python 的味道）→ "一个爱抠细节的 Python 库"，
#              它专门帮你"把数据按规矩检查一遍"。FastAPI 的请求体校验就是它在干
#   BaseModel 【三方库】拆开：Base（基础）+ Model（模型）。
#             它是 Pydantic 提供的**基类**，继承它之后，类的字段会被自动解析 + 校验 + 转 JSON
#   Field     【三方库】"字段"。它是个函数，用来给单个字段加规则
#             （必填/长度上限/数值范围/接口文档里的说明文字）
#   ⚠️ 注意这两个名字的写法差异：BaseModel 是大驼峰（类），Field 首字母大写但整体像函数名

from schemas.ai import ChatMessage
# 做什么：从本项目的 schemas/ai.py 里取出 ChatMessage 这个类
# 逐词：
#   schemas  【本地】项目里的 schemas 包。schema 原意"模式/纲要"，
#            在 Web 开发里指"数据的结构定义"（这个包里全是"请求/响应该长什么样"）
#   .ai      【本地】schemas 包里的 ai.py（普通 AI 问答用的模型定义）
#   ChatMessage  【本地】ai.py 里定义的类。拆开：Chat（聊天）+ Message（消息）
#                → "一条聊天消息"（里面只有 role 和 content 两个字段）
# 为什么不在本文件重新定义一遍：它和"普通 AI 问答"用的消息结构完全一样，
#   复用一个定义就行（这叫"复用"，代码少、改一处就够）

# ------------------------------------------------------------
# 请求体模型
# ------------------------------------------------------------


class RagChatRequest(BaseModel):
    # 做什么：定义一个类，代表"调用 /api/rag/chat 时前端要发过来的数据结构"
    # 逐词：
    #   class   【内置】"定义类"的关键字（类 = 一种自定义的数据类型）
    #   RagChatRequest  【自起名】拆开：Rag（RAG，检索增强生成）+ Chat（聊天）+ Request（请求）
    #                   → "RAG 聊天请求"。这个名字是项目自己起的，
    #                     惯例是"功能 + Request"，一眼能看出"这是请求体"
    #   (BaseModel)  【三方库】括号里是"父类" —— 表示继承 Pydantic 的 BaseModel。
    #                继承之后这个类就获得了"自动解析 + 校验"的能力：
    #                FastAPI 收到请求时会用它来解析 JSON，不合法就直接返回 422
    #   :        【内置】冒号 = "下面缩进的这几行都属于这个类"
    """RAG 问答请求体"""
    # 做什么：docstring（文档字符串）
    # 逐词：
    #   """..."""  【内置】三引号字符串。写在类/函数的第一句 → 自动变成"说明文档"，
    #              IDE 悬停时显示。注意它必须紧跟着 class 那一行，中间不能插别的代码
    question: str = Field(..., min_length=1, max_length=500, description="用户问题")
    # 做什么：声明一个字段，规定"前端必须传 question，是字符串，长度 1~500"
    # 逐词：
    #   question     【自起名】字段名。⚠️ 这个名字直接决定前端 JSON 里要写的键名 ——
    #                前端必须发 {"question": "..."}，改名就等于改接口
    #   :            【内置】冒号在类里表示"这是类的一个字段（属性）"
    #   str          【内置】类型：字符串。
    #                ⚠️ 位置容易看错：`question: str` 整体读作"question 这个字段是字符串类型"，
    #                   后面的 = Field(...) 才是"给它加规则"
    #   =            【内置】赋值：把这个字段的"规则对象"赋给它
    #   Field(...)   【三方库】Pydantic 的字段规则函数！逐词拆：
    #       Field   = 【三方库】上面 import 进来的那个函数
    #       ...     = 【内置】三个点叫 Ellipsis（省略号），是 Python 的一个特殊值。
    #                 在 Pydantic 里它表示"这个字段**必填**"（不能缺）。
    #                 ⚠️ 这个用法很反直觉：光看省略号完全猜不到是"必填"，属于要记住的约定
    #       min_length=1    【三方库】最少 1 个字符 → 防止前端传空串 ""
    #       max_length=500  【三方库】最多 500 个字符 → 防止有人把一整篇文章塞进来当问题
    #       description=... 【三方库】只是写进接口文档（/docs）的说明文字，**不影响校验**
    #   这些都是"关键字参数"（名字=值），所以顺序随便，读起来也清楚

    history: Optional[List[ChatMessage]] = Field(None, max_length=20, description="之前的对话，用于多轮")
    # 做什么：声明一个可选字段 history，最多 20 条，每条是一个 ChatMessage
    # 逐词：
    #   history   【自起名】"历史（对话）"
    #   Optional[...]  【标准库】"可选" —— 意思是这个字段**可以不给**，
    #                  不给时它的值就是 None（也就是"允许是 None"）
    #   List[...]      【标准库】列表；里面每一项都是冒号后面那个类型
    #   ChatMessage    【本地】schemas/ai.py 里的消息类（有 role 和 content）
    #                  ⚠️ 所以整体读作：可选的一段聊天记录，每条都是 ChatMessage。
    #                     写着嵌套了两种括号，从外往里读就不会晕：Optional[ List[ ChatMessage ] ]
    #   Field(None, ...)  【三方库】第一个参数是**默认值** —— 这里给 None，
    #                  表示"前端不传这个字段时，它的值就是 None"（配合 Optional 使用）
    #                  这和上面 question 的 Field(...) 正好相反：
    #                     Field(...)    → 必填
    #                     Field(None)   → 选填，默认 None
    #   max_length=20  【三方库】作用在**列表**上时表示"最多 20 项"
    # 前端把最近几轮对话传上来，后端拼进提示词就能"接着聊"
    # max_length=20 是防护：前端现在只传最近 6 条，但接口不能依赖前端自觉 ——
    #   不设上限的话，构造一个上千条 history 的请求就能把提示词撑爆（费钱 + 变慢 + 可能超长报错）

    top_k: Optional[int] = Field(None, ge=1, le=10, description="检索几块新闻，不传用默认值")
    # 做什么：声明一个可选字段 top_k，只能是 1~10 的整数
    # 逐词：
    #   top_k   【自起名】和 config/rag_conf.py 里的 TOP_K 是同一个概念：
    #           top（前几名）+ k（个数）→ "取最像的前 k 条"
    #           ⚠️ 注意这里用的是小写 top_k（因为 JSON 字段习惯用小写+下划线），
    #              配置里是常量所以全大写 TOP_K —— 同一件事，两种命名风格
    #   Optional[int]  【标准库+内置】可以不给，给的话必须是整数
    #   Field(None, ...)  【三方库】选填，默认 None（表示"没传 → 用配置里的默认值"）
    #   ge=1    【三方库】greater or equal（大于等于 1）。
    #           ⚠️ 这两个缩写是 Pydantic 的规定用法，不是 Python 关键字，记住即可：
    #              ge = ≥   gt = >   le = ≤   lt = <
    #   le=10   【三方库】less or equal（小于等于 10）
    # 为什么都要上下限：不加的话有人传 top_k=100，就会被塞 100 块新闻进提示词
    #   （token 暴涨、变慢、可能直接超长报错）—— 这不是防黑客，是接口设计的基本卫生
