CHUNK_SIZE = 400
# 做什么：规定"每一块最多多少个字"
# 逐词：
#   CHUNK    【自起名】"块" —— 文本切块领域的固定叫法（一块 = 一个 chunk）
#   SIZE     【通用名词】"大小"
#   400      【数字】单位是**字符数**，不是字节数（中文一个字算 1 个字符）
# 怎么选这个值：
#   太大 → 一块里混着好几件事，检索不准（问"特斯拉"可能命中一整篇无关长文）
#   太小 → 一句话被切碎，意思不完整
# 本项目的情况：新闻正文最长 192 字，所以 400 已经绰绰有余（这点在面试里要如实说）
# 谁在用：utils/splitter.py 的 split_text()（作为参数的默认值）

CHUNK_OVERLAP = 50
# 做什么：规定"相邻两块之间重叠多少个字"
# 逐词：
#   OVERLAP  【自起名】"重叠"—— 指前一块的尾巴在下一块开头再出现一次
#   50       【数字】重叠 50 个字符
# 为什么需要重叠：防止一句话正好被切在两个块的边界上。
#   有了重叠，就算"前半句在第 1 块末尾、后半句在第 2 块开头"，
#   第 2 块里也能看到这句话的前半部分，语义不会断
# 谁在用：utils/splitter.py 的 split_text()（第 4 步"给相邻块加重叠"）

CHUNK_SEPARATORS = ["\n\n", "\n", "。", "！", "？", ".", "!", "?", " ", ""]
# 做什么：规定"优先按什么符号切"，越靠前优先级越高
# 逐词（逐个元素看）：
#   CHUNK_SEPARATORS  【自起名】separator（分隔符）+ s（复数）
#   [ ... ]           【内置】方括号 = 列表。列表是**有顺序**的，这里的顺序 = 切块时的优先级
#   [0] "\n\n"   【转义字符】两个换行 = 空行 → 优先按"段落"切（意思最完整）
#               ⚠️ \n 是一个字符（换行符），不是两个字符。反斜杠表示"转义"，n 代表换行
#   [1] "\n"     单个换行 → 按"行"切
#   [2] "。"     中文句号 → 按句子切（这是中文语料的主力分隔符）
#   [3] "！"     中文感叹号
#   [4] "？"     中文问号
#   [5] "."      英文句点（注意和中文句号是两个不同字符）
#   [6] "!"      英文感叹号
#   [7] "?"      英文问号
#   [8] " "      空格 → 按词切
#   [9] ""       空字符串 → **兜底**：表示"什么符号都找不到了，只能按字数硬切"
# 为什么中文标点排在英文标点前面：本项目语料是中文，先按「。」切更贴合语言习惯。
#   课程里是英文标点在前，我们调了顺序 —— 这是有意的
# 谁在用：utils/splitter.py 的 split_text()（第 1 步"选出这一级要用的分隔符"）

