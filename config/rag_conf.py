TOP_K = 4
# 做什么：规定"每次检索取最像的前几块"
# 逐词：
#   TOP  【通用概念】"最前面的几名"（排行榜那种感觉）
#   K    【数学习惯字母】表示"个数"。检索领域大家都用 top_k 这个叫法 → "取前 k 条"
#   4    【数字】取 4 条。为什么不取 10：检索结果都会塞进提示词，条数越多越费钱也越慢，
#        而且不相关的资料会干扰模型。3~5 是常见取值
# 谁在用：utils/vectorstore.py 的 search()（作为 n_results）
#        crud/rag.py 的 retrieve()（不传 top_k 时用它兜底）

SCORE_THRESHOLD = float(os.getenv("SCORE_THRESHOLD", "0.55"))
# 做什么：定义"相似度分数线" —— 低于它就认为"新闻库里没有相关内容"，改走普通 AI 回答
# 逐词：
#   SCORE     【自起名】"分数"（这里指相似度 0~1）
#   THRESHOLD 【自起名】"阈值/门槛" —— 一个决策分界值。threshold 原意是"门槛"
#   =         【内置】赋值
#   float(...)  【内置】把括号里的东西转成小数。
#               ⚠️ 为什么必须转：环境变量读出来**永远都是字符串**（"0.55"），
#                  字符串不能直接和数字比大小（"0.55" > 0.5 会报 TypeError）。
#                  所以先 float() 转成 0.55 这个小数
#   os.getenv("SCORE_THRESHOLD", "0.55")  【标准库】读环境变量，找不到就用字符串 "0.55"
#               ⚠️ 注意默认值写的是字符串 "0.55"（带引号），因为 os.getenv 返回的永远是字符串，
#                  统一之后再 float() 转，逻辑更一致
# 相似度阈值（0~1，越高越像）
#   低于它 → 认为"新闻库里没有相关内容"，这次就不塞资料，直接用普通 AI 回答
#   高于它 → 把检索到的新闻一起发给模型，让它照着答并标注来源
#
# 为什么设计成"降级"而不是"拒答"：
#   拒答（直接说我不知道）体验很差 —— 用户打招呼都被拦。改成降级之后，
#   这个 AI 平时就是个正常助手，只有问到新闻里的事才自动带上资料。这才是"锦上添花"。
#
# 0.55 不是拍脑袋定的，是跑 tests/eval_retrieval.py 扫出来的：
#   那套评测 = 20 条"库里有答案"的正样本 + 18 条"库里没答案"的负样本，逐阈值扫一遍：
#     阈值   正样本判对   负样本判对   总正确率
#     0.45      100%        61%        82%
#     0.50      100%        72%        87%
#     0.55      100%        94%        97%   ← 拐点，就是选它的理由
#     0.60       85%        94%        90%   ← 再往上就开始杀正样本了
#   为什么拐点在 0.55：正样本的最低分是 0.5624，抬到 0.55 一条正样本都不会丢；
#   而误判的负样本大多落在 0.50~0.55 这个带里，等于白赚 22 个百分点。
#
# 实测分数分布（同一套样本，换过问法数字会变）：
#   正样本（库里真有答案）：0.5624 ~ 0.7812      负样本（库里没有答案）：0.0000 ~ 0.6141
#   两者仍然重叠，所以判错无法彻底避免 —— 靠下面三道保险把代价压小。
#
# 判错了怎么办？三道保险，所以代价很小：
#   ① 阈值取在拐点上（0.55），既不丢正样本，又挡掉大部分误判
#   ② 提示词里明确告诉模型"资料和问题无关就用你自己的知识回答"
#      —— 实测：把"你好"误判成 rag 模式时，模型照样正常回了问候语，没被资料带歪
#   ③ 寒暄类问题在代码里直接短路（见 crud/rag.py 的 is_small_talk）
# 谁在用：crud/rag.py 的 retrieve() 里那一行 mode = "rag" if top_score >= SCORE_THRESHOLD else "ai"
