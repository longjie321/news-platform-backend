BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# 做什么：算出"项目根目录"的绝对路径，存进 BASE_DIR
# 逐词（由内向外读，像剥洋葱）：
#   __file__      【内置】Python 自动给的变量 = "当前这个文件自己的路径"。
#                 ⚠️ 名字两边的双下划线表示"这是 Python 内部的特殊变量"，不是我们起的
#   os.path       【标准库】os 模块里管路径的子模块。注意它下面全是**函数**（要带括号）
#   .abspath(...) 【标准库】absolute path（绝对路径）→ 把相对路径换成"从盘符开始"的完整路径。
#                 用它的原因：绝对路径不受"当前工作目录"影响，从哪儿跑结果都一样
#   .dirname(...) 【标准库】directory name（目录名）→ 取出"这个文件所在的文件夹"。
#                 套两层 = 上一级的上一级
#   BASE_DIR      【自起名】本文件(在 config 里) → 上一级就是项目根。
#                 叫 BASE 是因为后面所有路径都基于它来拼
# 算出来的路径长这样：C:\Users\longjie\PycharmProjects\toutiao_backend
# ⚠️ 注意括号的配对：abspath(__file__) 先算，dirname 再套，dirname 又套一层


def _resolve_chroma_dir() -> str:
    # 做什么：定义函数，算出"向量库到底存在哪个目录"，返回字符串
    # 逐词：
    #   def              【内置】define，"定义函数"
    #   _resolve_chroma_dir  【自起名】拆开：
    #                    _（下划线，表示"内部专用"）+ resolve（解析、决定）+ chroma + dir（directory 目录）
    #                    → "解析出向量库目录"。开头下划线 = 别的地方不用直接调它
    #   ()               【内置】没有参数
    #   -> str           【标准库写法】箭头的部分是**返回类型标注**："这个函数会返回一个字符串"，
    #                    只写给人看，Python 运行时不管
    """
    算出向量库到底存在哪个目录
    返回：绝对路径（不是相对路径！）

    为什么这里必须用绝对路径（踩过的坑，别再改回 "./rag_data"）：
      ① chromadb.PersistentClient(path=...) 里的相对路径，是相对**当前工作目录**解析的
      ② 而 scripts/ingest_news.py 特意设计成"从任意目录都能跑"（它自己 sys.path 加了项目根）
      两件事一撞：从 scripts/ 目录里执行一次建索引，就会在 scripts/ 底下
      新长出一份 rag_data。而服务是从项目根启动的、读的是根目录那份 ——
      于是出现最难受的一类假成功："索引提示新增 20 篇成功"，线上却一条都没生效。
      改成绝对路径后，不管从哪个目录执行，读写的都是同一个库。

    环境变量 CHROMA_PERSIST_DIR 依然优先（docker-compose 里传的是 /app/rag_data）；
    若传的是相对路径，也按"相对项目根"处理，而不是相对当前工作目录。
    """
    # 这段三引号文字是 docstring（文档字符串）：写在函数第一句，鼠标悬停时显示的就是它
    env_dir = os.getenv("CHROMA_PERSIST_DIR")
    # 做什么：读环境变量 CHROMA_PERSIST_DIR
    # 逐词：
    #   env_dir        【自起名】env（环境变量）+ dir（目录）→ "从环境变量里读到的目录"
    #   os.getenv(...) 【标准库】这次**只传一个参数** —— 意思是"找不到就给我 None"，
    #                  而不是给个默认字符串。
    #                  为什么要 None：这样才能用 is None 区分两种情况：
    #                    「压根没配这个环境变量」 vs 「配了但配成空字符串」
    #   CHROMA_PERSIST_DIR  【约定】环境变量名。拆开：
    #                  CHROMA（向量库名）+ PERSIST（persist 持久化，指"存到磁盘"）+ DIR
    #                  这个名字是项目自己定的（docker-compose.yml 里设置的也是它）
    if not env_dir:
        # 做什么：判断"没读到"（None 或空字符串都算没配）
        # 逐词：
        #   if    【内置】"如果"
        #   not   【内置】"取反"。
        #         ⚠️ 这里 not 同时管住 None 和 ""，两种情况都进这个分支 —— 正是我们想要的：
        #            "没配"和"配成空"在这一步处理方式一样
        return os.path.join(BASE_DIR, "rag_data")
        # 做什么：用系统分隔符把"项目根"和"rag_data"拼成一个路径，然后返回
        # 逐词：
        #   return         【内置】返回，函数到此结束
        #   os.path.join   【标准库】把两段路径拼起来。它聪明在"用当前系统的分隔符"：
        #                  Windows 拼出 …\toutiao_backend\rag_data，Linux 拼出 …/toutiao_backend/rag_data
        #                  ⚠️ 所以别自己写 "路径1" + "/" + "路径2"（在 Windows 上会混用斜杠）
        #   BASE_DIR       【本地】上面算出来的项目根目录
        #   "rag_data"     【自起名】文件夹名。rag（检索增强生成）+ data（数据）
        # 默认：项目根/rag_data（绝对路径）
    if os.path.isabs(env_dir):
        # 做什么：如果环境变量给的是绝对路径（比如容器里的 /app/rag_data），直接用
        # 逐词：
        #   os.path.isabs  【标准库】is + absolute = "是不是绝对路径"。
        #                   Windows 上判断"开头是不是盘符"，Linux 上判断"开头是不是 /"
        return env_dir
        # 已经是绝对路径，直接用（不用再拼 BASE_DIR）
    return os.path.join(BASE_DIR, env_dir)
    # 做什么：剩下的情况 = 环境变量给了"相对路径"（比如 ./my_rag），按"相对项目根"处理
    # 逐词：os.path.join 同上
    # 为什么这么写：如果直接返回 env_dir，相对路径又会依赖"当前工作目录"，
    #   那就等于把坑又挖回来了。拼上 BASE_DIR 就永远锚定在项目根


CHROMA_DIR = _resolve_chroma_dir()
# 做什么：调用上面那个函数，把算出来的目录存进常量 CHROMA_DIR
# 逐词：
#   CHROMA_DIR            【自起名】常量名（CHROMA + DIR）
#   _resolve_chroma_dir   【本地】本文件上面定义的函数
#   ()                    【内置】括号 = 调用。⚠️ 少了括号，CHROMA_DIR 就变成了"函数本身"而不是路径，
#                         后面 chromadb 会报奇怪的错
# 向量存到哪个目录（重启服务数据还在）
# 谁在用：utils/vectorstore.py 的 _collection() 和 reset()（都写成 path=CHROMA_DIR）

